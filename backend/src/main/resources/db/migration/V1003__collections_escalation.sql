--     BRCLXN.050  manual escalation of one or several invoices to the team lead or a designated
--                 authority, with history and notifications
--     BRCLXN.055  broken promises feed the escalation (BROKEN_PROMISES_COUNT)
--   Design: docs/architecture/COLLECTIONS_DESIGN.md sections 3 (V893 of the design is this
--   V1003), 4.3, 7 (workflow CLX_ESCALATION, seeded in V1000) and 12 (row C1-B).
