-- iNXT BrokerVerse - V1004 Collections (BRD-4) unapplied payments, collector side (wave C1-C).
--   Requirements: docs/requirements/BDOI_CLXN_BRD_SPEC.md
--     BRCLXN.030/032  request application of an unapplied payment (Collection Handler, Unapplied
--                     Payment Handler) through the port UnappliedDispositionRequests
--     BRCLXN.031/033  document the collector disposition (append-only, with history)
--     BRCLXN.034-036  list of unapplied payments as of today (read from Cashiering through
--                     UnappliedDirectory; never copied)
--     BRCLXN.037-039  LOV CLX_UPP_DISPOSITION (V1000) with attributes requires_invoice and
--                     cashiering_action (clx_lov_attribute)
--     BRCLXN.040      history kept after the payment is applied or refunded
--     BRCLXN.041/042  daily "For Application To Invoice" text file (job CLX_APPLICATION_FILE)
--     BRCLXN.047/048  invoice number mandatory for "for application to invoice", validated by
--                     CLX_INVOICE_NO_PATTERN and the invoice ledger
--   Design: docs/architecture/COLLECTIONS_DESIGN.md sections 3 (V894 of the design is this V1004),
--   4.4 and 12 (row C1-C).
--   Cashiering's unapplied items are referenced by their plain reference (UNP-...), as the design
--   rules for Operations keys; the request table also keeps the p.60 payment fields of the file as
--   a snapshot taken at request time.
