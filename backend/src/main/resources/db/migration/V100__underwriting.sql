-- =====================================================================================
-- iNXT FinVerse - V100 Underwriting: products, quotations, policies, risks,
-- endorsements and marine open covers.
-- Premium figures are stored per financial document (policy = original issue,
-- endorsement = change) with the same column set, so registers can union them.
-- =====================================================================================

create table uw_product (
    id                      bigint generated by default as identity primary key,
    version                 bigint         not null default 0,
    company_id              bigint         not null references org_company (id),
    code                    varchar(20)    not null,
    name                    varchar(120)   not null,
    business_line           varchar(20)    not null,
    default_commission_rate numeric(19, 8) not null default 0 check (default_commission_rate between 0 and 100),
    upr_basis               varchar(20)    not null,
    dst_rate                numeric(19, 8) not null default 0 check (dst_rate >= 0),
    vat_rate                numeric(19, 8) not null default 0 check (vat_rate >= 0),
    lgt_rate                numeric(19, 8) not null default 0 check (lgt_rate >= 0),
    fst_rate                numeric(19, 8) not null default 0 check (fst_rate >= 0),
    premium_tax_rate        numeric(19, 8) not null default 0 check (premium_tax_rate >= 0),
    policy_fee              numeric(19, 2) not null default 0 check (policy_fee >= 0),
    open_cover_allowed      boolean        not null default false,
    record_status           varchar(30)    not null,
    authorized_by           varchar(50),
    authorized_at           timestamptz,
    created_at              timestamptz    not null,
    created_by              varchar(50)    not null,
    updated_at              timestamptz,
    updated_by              varchar(50),
    constraint uq_uw_product_code unique (company_id, code)
);

create table uw_open_cover (
    id                  bigint generated by default as identity primary key,
    version             bigint         not null default 0,
    company_id          bigint         not null references org_company (id),
    branch_id           bigint         not null references org_branch (id),
    open_cover_no       varchar(40)    not null,
    product_id          bigint         not null references uw_product (id),
    customer_party_id   bigint         not null references pty_party (id),
    insured_name        varchar(200)   not null,
    period_from         date           not null,
    period_to           date           not null,
    currency            varchar(3)     not null,
    limit_per_shipment  numeric(19, 2) not null check (limit_per_shipment > 0),
    annual_limit        numeric(19, 2) not null check (annual_limit > 0),
    rate                numeric(19, 8) not null check (rate >= 0),
    cargo_description   varchar(300),
    record_status       varchar(30)    not null,
    authorized_by       varchar(50),
    authorized_at       timestamptz,
    created_at          timestamptz    not null,
    created_by          varchar(50)    not null,
    updated_at          timestamptz,
    updated_by          varchar(50),
    constraint uq_uw_open_cover_no unique (company_id, open_cover_no),
    constraint ck_uw_open_cover_period check (period_to >= period_from)
);

create table uw_quotation (
    id                     bigint generated by default as identity primary key,
    version                bigint         not null default 0,
    company_id             bigint         not null references org_company (id),
    branch_id              bigint         not null references org_branch (id),
    quotation_no           varchar(40)    not null,
    product_id             bigint         not null references uw_product (id),
    customer_party_id      bigint         not null references pty_party (id),
    insured_name           varchar(200)   not null,
    source_type            varchar(10)    not null check (source_type in ('DIRECT', 'AGENT', 'BROKER')),
    intermediary_party_id  bigint references pty_party (id),
    issue_date             date           not null,
    validity_days          integer        not null check (validity_days between 1 and 365),
    period_from            date           not null,
    period_to              date           not null,
    currency               varchar(3)     not null,
    share_pct              numeric(19, 8) not null check (share_pct > 0 and share_pct <= 100),
    commission_rate        numeric(19, 8) not null default 0 check (commission_rate between 0 and 100),
    status                 varchar(20)    not null,
    current_iteration      integer        not null default 1,
    submitted_by           varchar(50),
    decided_by             varchar(50),
    decided_at             timestamptz,
    decision_reason        varchar(200),
    converted_policy_id    bigint,
    created_at             timestamptz    not null,
    created_by             varchar(50)    not null,
    updated_at             timestamptz,
    updated_by             varchar(50),
    constraint uq_uw_quotation_no unique (company_id, quotation_no),
    constraint ck_uw_quotation_period check (period_to >= period_from)
);
create index ix_uw_quotation_status on uw_quotation (company_id, status, issue_date);

create table uw_quotation_iteration (
    id              bigint generated by default as identity primary key,
    quotation_id    bigint         not null references uw_quotation (id),
    iteration_no    integer        not null,
    sum_insured     numeric(19, 2) not null check (sum_insured >= 0),
    gross_premium   numeric(19, 2) not null check (gross_premium >= 0),
    discount        numeric(19, 2) not null default 0 check (discount >= 0),
    loading         numeric(19, 2) not null default 0 check (loading >= 0),
    charges         numeric(19, 2) not null default 0 check (charges >= 0),
    remarks         varchar(300),
    created_at      timestamptz    not null,
    created_by      varchar(50)    not null,
    constraint uq_uw_quotation_iteration unique (quotation_id, iteration_no)
);

create table uw_policy (
    id                     bigint generated by default as identity primary key,
    version                bigint         not null default 0,
    company_id             bigint         not null references org_company (id),
    branch_id              bigint         not null references org_branch (id),
    policy_no              varchar(40)    not null,
    product_id             bigint         not null references uw_product (id),
    customer_party_id      bigint         not null references pty_party (id),
    insured_name           varchar(200)   not null,
    source_type            varchar(10)    not null check (source_type in ('DIRECT', 'AGENT', 'BROKER')),
    intermediary_party_id  bigint references pty_party (id),
    issue_date             date           not null,
    period_from            date           not null,
    period_to              date           not null,
    currency               varchar(3)     not null,
    uw_year                integer        not null,
    business_type          varchar(30)    not null check (business_type in ('DIRECT', 'DIRECT_WITH_COINSURANCE')),
    share_pct              numeric(19, 8) not null check (share_pct > 0 and share_pct <= 100),
    coinsurer_party_id     bigint references pty_party (id),
    coinsurance_leader     boolean        not null default false,
    discount_rate          numeric(19, 8) not null default 0 check (discount_rate between 0 and 100),
    loading_rate           numeric(19, 8) not null default 0 check (loading_rate >= 0),
    open_cover_id          bigint references uw_open_cover (id),
    quotation_id           bigint references uw_quotation (id),
    status                 varchar(20)    not null,
    -- premium figures of the original issue (see uw_endorsement for changes)
    sum_insured            numeric(19, 2) not null default 0,
    our_sum_insured        numeric(19, 2) not null default 0,
    gross_premium          numeric(19, 2) not null default 0,
    discount_amount        numeric(19, 2) not null default 0,
    loading_amount         numeric(19, 2) not null default 0,
    net_premium            numeric(19, 2) not null default 0,
    our_gross_premium      numeric(19, 2) not null default 0,
    our_discount           numeric(19, 2) not null default 0,
    our_loading            numeric(19, 2) not null default 0,
    our_net_premium        numeric(19, 2) not null default 0,
    coinsurer_premium      numeric(19, 2) not null default 0,
    billed_premium         numeric(19, 2) not null default 0,
    dst                    numeric(19, 2) not null default 0,
    vat                    numeric(19, 2) not null default 0,
    lgt                    numeric(19, 2) not null default 0,
    fst                    numeric(19, 2) not null default 0,
    premium_tax            numeric(19, 2) not null default 0,
    policy_fee             numeric(19, 2) not null default 0,
    total_due              numeric(19, 2) not null default 0,
    commission_rate        numeric(19, 8) not null default 0,
    commission             numeric(19, 2) not null default 0,
    withholding_rate       numeric(19, 8) not null default 0,
    withholding_tax        numeric(19, 2) not null default 0,
    net_commission         numeric(19, 2) not null default 0,
    exchange_rate          numeric(19, 8),
    -- workflow and accounting
    submitted_by           varchar(50),
    submitted_at           timestamptz,
    approved_by            varchar(50),
    approved_at            timestamptz,
    approval_date          date,
    rejection_reason       varchar(200),
    debit_note_no          varchar(40),
    credit_note_no         varchar(40),
    premium_batch_no       varchar(40),
    commission_batch_no    varchar(40),
    cancelled_on           date,
    created_at             timestamptz    not null,
    created_by             varchar(50)    not null,
    updated_at             timestamptz,
    updated_by             varchar(50),
    constraint uq_uw_policy_no unique (company_id, policy_no),
    constraint ck_uw_policy_period check (period_to >= period_from),
    constraint ck_uw_policy_coins check (business_type = 'DIRECT' or coinsurer_party_id is not null)
);
create index ix_uw_policy_status on uw_policy (company_id, status, issue_date);
create index ix_uw_policy_approval on uw_policy (company_id, approval_date);
create index ix_uw_policy_expiry on uw_policy (company_id, period_to);
create index ix_uw_policy_customer on uw_policy (customer_party_id);
create index ix_uw_policy_open_cover on uw_policy (open_cover_id);

create table uw_policy_risk (
    id                  bigint generated by default as identity primary key,
    policy_id           bigint         not null references uw_policy (id),
    line_no             integer        not null,
    description         varchar(300)   not null,
    sum_insured         numeric(19, 2) not null check (sum_insured >= 0),
    rate                numeric(19, 8) not null default 0 check (rate >= 0),
    premium             numeric(19, 2) not null check (premium >= 0),
    occupation          varchar(120),
    accumulation_zone   varchar(40),
    vessel_name         varchar(120),
    voyage_from         varchar(80),
    voyage_to           varchar(80),
    sail_date           date,
    bl_no               varchar(40),
    bl_date             date,
    lc_no               varchar(40),
    bank_name           varchar(120),
    valuation_basis     varchar(120),
    -- deferred: replacing the risks of a draft inserts new lines before orphans are deleted
    constraint uq_uw_policy_risk unique (policy_id, line_no) deferrable initially deferred
);
create index ix_uw_risk_zone on uw_policy_risk (accumulation_zone);

create table uw_endorsement (
    id                     bigint generated by default as identity primary key,
    version                bigint         not null default 0,
    policy_id              bigint         not null references uw_policy (id),
    endorsement_no         integer        not null check (endorsement_no > 0),
    endorsement_type       varchar(20)    not null
        check (endorsement_type in ('ADDITIONAL', 'REFUND', 'RENEWAL', 'CANCELLATION', 'NIL')),
    issue_date             date           not null,
    effective_date         date           not null,
    new_period_from        date,
    new_period_to          date,
    description            varchar(500)   not null,
    status                 varchar(20)    not null,
    sum_insured            numeric(19, 2) not null default 0,
    our_sum_insured        numeric(19, 2) not null default 0,
    gross_premium          numeric(19, 2) not null default 0,
    discount_amount        numeric(19, 2) not null default 0,
    loading_amount         numeric(19, 2) not null default 0,
    net_premium            numeric(19, 2) not null default 0,
    our_gross_premium      numeric(19, 2) not null default 0,
    our_discount           numeric(19, 2) not null default 0,
    our_loading            numeric(19, 2) not null default 0,
    our_net_premium        numeric(19, 2) not null default 0,
    coinsurer_premium      numeric(19, 2) not null default 0,
    billed_premium         numeric(19, 2) not null default 0,
    dst                    numeric(19, 2) not null default 0,
    vat                    numeric(19, 2) not null default 0,
    lgt                    numeric(19, 2) not null default 0,
    fst                    numeric(19, 2) not null default 0,
    premium_tax            numeric(19, 2) not null default 0,
    policy_fee             numeric(19, 2) not null default 0,
    total_due              numeric(19, 2) not null default 0,
    commission_rate        numeric(19, 8) not null default 0,
    commission             numeric(19, 2) not null default 0,
    withholding_rate       numeric(19, 8) not null default 0,
    withholding_tax        numeric(19, 2) not null default 0,
    net_commission         numeric(19, 2) not null default 0,
    exchange_rate          numeric(19, 8),
    submitted_by           varchar(50),
    submitted_at           timestamptz,
    approved_by            varchar(50),
    approved_at            timestamptz,
    approval_date          date,
    rejection_reason       varchar(200),
    debit_note_no          varchar(40),
    credit_note_no         varchar(40),
    premium_batch_no       varchar(40),
    commission_batch_no    varchar(40),
    created_at             timestamptz    not null,
    created_by             varchar(50)    not null,
    updated_at             timestamptz,
    updated_by             varchar(50),
    constraint uq_uw_endorsement unique (policy_id, endorsement_no)
);
create index ix_uw_endorsement_approval on uw_endorsement (approval_date);
create index ix_uw_endorsement_status on uw_endorsement (status, issue_date);

alter table uw_quotation
    add constraint fk_uw_quotation_policy foreign key (converted_policy_id) references uw_policy (id);
