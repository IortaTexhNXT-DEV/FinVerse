create table rnw_bucket_rule_set (
    id              bigint generated by default as identity primary key,
    version         bigint       not null default 0,
    company_id      bigint       not null references org_company (id),
    version_no      integer      not null,
    status          varchar(20)  not null,
    effective_from  date         not null,
    description     varchar(200),
    submitted_by    varchar(50),
    submitted_at    timestamptz,
    approved_by     varchar(50),
    approved_at     timestamptz,
    decision_remarks varchar(200),
    created_at      timestamptz  not null,
    created_by      varchar(50)  not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint uq_rnw_bucket_rule_set unique (company_id, version_no),
    constraint ck_rnw_bucket_rule_set_status check (status in ('DRAFT', 'SUBMITTED', 'ACTIVE', 'RETIRED', 'REJECTED'))
);
create unique index uq_rnw_bucket_rule_set_active on rnw_bucket_rule_set (company_id) where status = 'ACTIVE';

create table rnw_bucket_rule (
    id              bigint generated by default as identity primary key,
    version         bigint       not null default 0,
    rule_set_id     bigint       not null references rnw_bucket_rule_set (id),
    priority        integer      not null,
    check_code      varchar(40),
    severity        varchar(20),
    outcome         varchar(20)  not null,
    result_bucket   varchar(20)  not null,
    created_at      timestamptz  not null,
    created_by      varchar(50)  not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint uq_rnw_bucket_rule unique (rule_set_id, priority),
    constraint ck_rnw_bucket_rule_outcome check (outcome in ('FAIL', 'WARN')),
    constraint ck_rnw_bucket_rule_bucket check (result_bucket in ('CLEAN', 'REVIEW', 'EXCEPTION')),
    -- A failed check never gives CLEAN (BRRN.023 negative scenario).
    constraint ck_rnw_bucket_rule_no_clean_fail check (not (outcome = 'FAIL' and result_bucket = 'CLEAN'))
);

create table rnw_decision_matrix (
