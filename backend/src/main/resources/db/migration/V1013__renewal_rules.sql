-- =====================================================================================
-- iNXT BrokerVerse - V1013 Renewal (BRD-6) rules: non-renewable risk codes, check settings,
-- versioned bucket rule sets and decision matrices, the package code map of migrated policies and
-- the package choices of the Renewal processing team.
--   BRRN.009       non-renewable risk codes (maker-checker, end-dated, never deleted)
--   BRRN.020/023   check settings and bucket rules; a failed check never gives CLEAN (database check
--                  here and a service guard)
--   BRRN.031/034   decision matrix: priority, criteria, disposition, AUTO / MANUAL
--   DMQ36          package remapping at sanitation: the PACKAGE code map loaded by the migration and
--                  maintained in Renewal; choices of the processing team with maker and checker
--   Design: docs/architecture/RENEWAL_DESIGN.md sections 4.2, 8 and 13.1. The rule sets and the
--   matrix ship without content (RQ01, RQ24); seed content is in V1910. The check settings carry the
--   default severities of the design.
-- =====================================================================================

create table rnw_non_renewable_risk_code (
    id              bigint generated by default as identity primary key,
    version         bigint       not null default 0,
    company_id      bigint       not null references org_company (id),
    risk_code       varchar(20)  not null,
    line_code       varchar(30),
    reason          varchar(200) not null,
    effective_from  date         not null,
    effective_to    date,
    record_status   varchar(30)  not null,
    authorized_by   varchar(50),
    authorized_at   timestamptz,
    created_at      timestamptz  not null,
    created_by      varchar(50)  not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint ck_rnw_nrr_dates check (effective_to is null or effective_to >= effective_from)
);
create index ix_rnw_nrr_code on rnw_non_renewable_risk_code (company_id, risk_code);

