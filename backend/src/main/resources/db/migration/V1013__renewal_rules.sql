create table rnw_decision_rule (
    id                    bigint generated by default as identity primary key,
    version               bigint       not null default 0,
    matrix_id             bigint       not null references rnw_decision_matrix (id),
    priority              integer      not null,
    segment               varchar(40),
    line_code             varchar(30),
    product_code          varchar(20),
    mortgaged             boolean,
    bucket                varchar(20),
    claims_condition      varchar(20),
    endorsement_condition varchar(20),
    payment_condition     varchar(20),
    days_from             integer,
    days_to               integer,
    outcome_disposition   varchar(20)  not null,
    automation            varchar(10)  not null,
    letter_hint           varchar(10),
    created_at            timestamptz  not null,
    created_by            varchar(50)  not null,
    updated_at            timestamptz,
    updated_by            varchar(50),
    constraint uq_rnw_decision_rule unique (matrix_id, priority),
    constraint ck_rnw_decision_rule_bucket check (bucket is null or bucket in ('CLEAN', 'REVIEW')),
    constraint ck_rnw_decision_rule_claims check (claims_condition is null or claims_condition in ('NONE', 'OPEN', 'PAID', 'TOTAL_LOSS')),
    constraint ck_rnw_decision_rule_endorsement check (endorsement_condition is null or endorsement_condition in ('NONE', 'POSTED_IN_TERM', 'PENDING')),
    constraint ck_rnw_decision_rule_payment check (payment_condition is null or payment_condition in ('PAID', 'OUTSTANDING', 'DP')),
    constraint ck_rnw_decision_rule_days check (days_from is null or days_to is null or days_from <= days_to),
    constraint ck_rnw_decision_rule_outcome check (outcome_disposition in ('FOR_RENEWAL', 'NOT_FOR_RENEWAL',
        'FOR_QUOTATION', 'FOR_PROPOSAL', 'LOST_BUSINESS')),
    constraint ck_rnw_decision_rule_automation check (automation in ('AUTO', 'MANUAL')),
    constraint ck_rnw_decision_rule_letter check (letter_hint is null or letter_hint in ('RA', 'NFR', 'NAL'))
);

create table rnw_package_map (
    id                     bigint generated by default as identity primary key,
    version                bigint        not null default 0,
    company_id             bigint        not null references org_company (id),
    legacy_package_code    varchar(40)   not null,
    legacy_package_version varchar(20),
    risk_code              varchar(20),
    insurer_code           varchar(30),
    si_from                numeric(19, 2),
    si_to                  numeric(19, 2),
    action                 varchar(10)   not null,
    product_code           varchar(20),
    product_version_no     integer,
    map_version            integer       not null default 1,
    source                 varchar(20)   not null,
    remarks                varchar(200),
    record_status          varchar(30)   not null,
    authorized_by          varchar(50),
    authorized_at          timestamptz,
    created_at             timestamptz   not null,
    created_by             varchar(50)   not null,
    updated_at             timestamptz,
    updated_by             varchar(50),
    constraint ck_rnw_package_map_action check (action in ('MAP', 'REJECT')),
    constraint ck_rnw_package_map_target check (action = 'REJECT' or (product_code is not null and product_version_no is not null)),
    constraint ck_rnw_package_map_source check (source in ('MIGRATION', 'SETUP', 'CHOICE')),
    constraint ck_rnw_package_map_band check (si_from is null or si_to is null or si_from <= si_to)
);
create index ix_rnw_package_map_code on rnw_package_map (company_id, legacy_package_code);

