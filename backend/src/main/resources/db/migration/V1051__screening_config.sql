-- =====================================================================================
-- iNXT BrokerVerse - V1051 Sanction Screening (BRD-10) versioned configuration (wave S1-A).
--   Requirements: docs/requirements/BDOI_SANC_BRD_SPEC.md
--     SNSRP-101  matching criteria (scr_match_rule)
--     SNSRP-102  risk categories and tagging rules (scr_risk_category, scr_risk_rule)
--     SNSRP-103  approval / escalation matrix (scr_approval_route; SNSRP-703)
--     SNSRP-104  review templates (scr_template, scr_template_field)
--     SNSRP-105  STR template and extraction layout (scr_str_layout, scr_str_layout_column; SQ09)
--     SNSRP-106  case assignment matrix (scr_assignment_rule)
--     SNSRP-108  SLA matrix (scr_sla_rule)
--     SNSRP-109  maker-checker: DRAFT -> PENDING -> ACTIVE / REJECTED, SUPERSEDED on the date of
--                the next version (scr_config_version)
--     SNSRP-701  validation rules (scr_validation_rule)
--   Design: docs/architecture/SANCTION_SCREENING_DESIGN.md section 4.1. Every rule row belongs to
--   one version; an ACTIVE version is never edited (the service refuses it), a change is a new
--   version. TEMPLATE versions are kept per template type (scope); the other types have scope ''.
--   No seed data here: the seed versions come with db/seed/V1950.
-- =====================================================================================

create table scr_config_version (
    id               bigint generated by default as identity primary key,
    version          bigint        not null default 0,
    company_id       bigint        not null references org_company (id),
    config_type      varchar(30)   not null,
    scope            varchar(30)   not null default '',
    version_no       integer       not null,
    status           varchar(20)   not null,
    effective_from   date          not null,
    change_note      varchar(1000),
    base_version_id  bigint        references scr_config_version (id),
    submitted_by     varchar(50),
    submitted_at     timestamptz,
    decided_by       varchar(50),
    decided_at       timestamptz,
    decision_reason  varchar(1000),
    diff             text,
    created_at       timestamptz   not null,
    created_by       varchar(50)   not null,
    updated_at       timestamptz,
    updated_by       varchar(50),
    constraint uq_scr_config_version unique (company_id, config_type, scope, version_no),
    constraint ck_scr_config_version_type check (config_type in ('MATCH_CRITERIA', 'RISK_RULES',
        'APPROVAL_MATRIX', 'ASSIGNMENT_MATRIX', 'SLA_MATRIX', 'VALIDATION_RULES', 'TEMPLATE', 'STR_LAYOUT')),
    constraint ck_scr_config_version_status check (status in ('DRAFT', 'PENDING', 'ACTIVE', 'SUPERSEDED',
        'REJECTED')),
    constraint ck_scr_config_version_scope check ((config_type = 'TEMPLATE') = (scope <> ''))
);
-- FR-SS-010 R1: at most one DRAFT or PENDING version per type, one ACTIVE version per type and date.
create unique index uq_scr_config_version_open on scr_config_version (company_id, config_type, scope)
    where status in ('DRAFT', 'PENDING');
create unique index uq_scr_config_version_active on scr_config_version (company_id, config_type, scope,
    effective_from) where status = 'ACTIVE';
create index ix_scr_config_version_status on scr_config_version (status);

create table scr_match_rule (
    id                  bigint generated by default as identity primary key,
    version             bigint        not null default 0,
    version_id          bigint        not null references scr_config_version (id) on delete cascade,
    sort_order          integer       not null,
    list_type           varchar(30)   not null,
    subject_type        varchar(20)   not null,
    algorithm           varchar(20)   not null,
    threshold           numeric(5,4)  not null,
    match_fields        varchar(200)  not null,
    min_score_for_case  numeric(5,4)  not null,
    created_at          timestamptz   not null,
    created_by          varchar(50)   not null,
    updated_at          timestamptz,
    updated_by          varchar(50),
    constraint uq_scr_match_rule unique (version_id, list_type, subject_type, algorithm),
    constraint ck_scr_match_rule_subject check (subject_type in ('INDIVIDUAL', 'ENTITY')),
    constraint ck_scr_match_rule_algorithm check (algorithm in ('EXACT', 'PHONETIC', 'FUZZY')),
    constraint ck_scr_match_rule_threshold check (threshold between 0 and 1
        and min_score_for_case between threshold and 1)
);
create index ix_scr_match_rule_version on scr_match_rule (version_id);

create table scr_risk_category (
    id               bigint generated by default as identity primary key,
    version          bigint        not null default 0,
    version_id       bigint        not null references scr_config_version (id) on delete cascade,
    code             varchar(30)   not null,
    name             varchar(100)  not null,
    tier             integer       not null,
    kyc_risk_rating  varchar(30)   not null,
    tags             varchar(200)  not null default '',
    case_type        varchar(30),
    requires_edd     boolean       not null default false,
    created_at       timestamptz   not null,
    created_by       varchar(50)   not null,
    updated_at       timestamptz,
    updated_by       varchar(50),
    constraint uq_scr_risk_category unique (version_id, code),
    constraint ck_scr_risk_category_tier check (tier > 0)
);
create index ix_scr_risk_category_version on scr_risk_category (version_id);

create table scr_risk_rule (
    id              bigint generated by default as identity primary key,
    version         bigint        not null default 0,
    version_id      bigint        not null references scr_config_version (id) on delete cascade,
    priority        integer       not null,
    category_code   varchar(30)   not null,
    condition_attr  varchar(30)   not null,
    operator        varchar(10)   not null,
    rule_values     varchar(500)  not null,
    created_at      timestamptz   not null,
    created_by      varchar(50)   not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint uq_scr_risk_rule unique (version_id, priority),
    constraint ck_scr_risk_rule_attr check (condition_attr in ('MATCH_LIST_TYPE', 'MATCH_STATUS', 'PEP',
        'NATIONALITY', 'OCCUPATION', 'SOURCE_OF_FUNDS', 'CLIENT_TYPE', 'MARKET_SEGMENT')),
    constraint ck_scr_risk_rule_operator check (operator in ('EQ', 'IN', 'NOT_IN'))
);
create index ix_scr_risk_rule_version on scr_risk_rule (version_id);

create table scr_approval_route (
