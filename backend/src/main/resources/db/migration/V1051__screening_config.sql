    updated_by  varchar(50),
    constraint ck_scr_validation_rule_kind check (rule_kind in ('TEMPLATE_COMPLETE', 'DOCUMENT_TYPES_PRESENT',
        'DISPOSITION_ALLOWED', 'RECOMMENDATION_PRESENT', 'STR_FLAG_CONSISTENT'))
);
create index ix_scr_validation_rule_version on scr_validation_rule (version_id);

