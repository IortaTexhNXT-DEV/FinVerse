    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint uq_scr_assignment_rule unique (version_id, sort_order),
    constraint ck_scr_assignment_rule_target check (team_role is not null or user_name is not null),
    constraint ck_scr_assignment_rule_balancing check (balancing in ('ROUND_ROBIN', 'LEAST_OPEN', 'NONE'))
);
create index ix_scr_assignment_rule_version on scr_assignment_rule (version_id);

create table scr_sla_rule (
    id                   bigint generated by default as identity primary key,
    version              bigint        not null default 0,
    version_id           bigint        not null references scr_config_version (id) on delete cascade,
    stage                varchar(30)   not null,
    case_type            varchar(30),
    risk_category        varchar(30),
    sla_hours            integer       not null,
    reminder_lead_hours  integer       not null default 0,
    escalate_to_role     varchar(50)   not null,
    calendar             varchar(20)   not null,
    created_at           timestamptz   not null,
    created_by           varchar(50)   not null,
    updated_at           timestamptz,
    updated_by           varchar(50),
    constraint ck_scr_sla_rule_hours check (sla_hours > 0 and reminder_lead_hours >= 0
        and reminder_lead_hours < sla_hours),
    constraint ck_scr_sla_rule_calendar check (calendar in ('CALENDAR', 'WORKING'))
);
create unique index uq_scr_sla_rule on scr_sla_rule (version_id, stage, coalesce(case_type, ''),
    coalesce(risk_category, ''));

create table scr_validation_rule (
    id          bigint generated by default as identity primary key,
    version     bigint        not null default 0,
    version_id  bigint        not null references scr_config_version (id) on delete cascade,
    stage       varchar(30),
    case_type   varchar(30),
    rule_kind   varchar(40)   not null,
    parameters  varchar(500),
