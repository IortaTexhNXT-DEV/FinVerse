    updated_by      varchar(50),
    constraint uq_scr_approval_route unique (version_id, sort_order),
    constraint ck_scr_approval_route_kind check (approver_kind in ('UNIT_HEAD', 'ROLE', 'USER'))
);
create index ix_scr_approval_route_version on scr_approval_route (version_id);

create table scr_assignment_rule (
    id              bigint generated by default as identity primary key,
    version         bigint        not null default 0,
    version_id      bigint        not null references scr_config_version (id) on delete cascade,
    sort_order      integer       not null,
    case_type       varchar(30),
    trigger_code    varchar(30),
    risk_category   varchar(30),
    marketing_unit  varchar(30),
    client_type     varchar(20),
    team_role       varchar(50),
    user_name       varchar(50),
    balancing       varchar(20)   not null,
    created_at      timestamptz   not null,
