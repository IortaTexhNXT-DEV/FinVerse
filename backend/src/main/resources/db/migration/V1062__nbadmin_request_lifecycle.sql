alter table sec_access_change_log drop constraint ck_sec_access_change_subject;
alter table sec_access_change_log add constraint ck_sec_access_change_subject
    check (subject_type in ('USER', 'ROLE', 'EXTERNAL_USER'));

-- ---------- Grants ---------------------------------------------------------------------------
-- The Requestor attaches bulk request files (BRD 1.009) through the bulk upload framework.
insert into sec_role_permission (role_id, permission)
select r.id, 'BULK_PROCESS' from sec_role r
where r.code = 'UAM_REQUESTOR'
  and not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = 'BULK_PROCESS');

-- ---------- Behaviour switches: the implement-request flow is live -----------------------------
update sys_parameter
set param_value = 'false',
    description = 'Emergency path: when true, the System Administrator may create and edit roles directly on the Roles screen (audited, alert UAM_DIRECT_ROLE_EDIT); when false, a role changes only by implementing an approved group-profile request (PQ17)',
    updated_at = now(), updated_by = 'SYSTEM'
where param_key = 'UAM_DIRECT_ROLE_EDIT';

update sys_parameter
set param_value = 'false',
    description = 'When true, an approved group-profile or role-permission request applies at its last approval; when false it waits for the System Administrator to implement it (BRD-11 p.6; UQ03)',
    updated_at = now(), updated_by = 'SYSTEM'
where param_key = 'UAM_ROLE_APPLY_ON_APPROVAL';

-- ---------- Retention (design section 12): closed requests are reviewed, never deleted --------
insert into nba_retention_rule (record_type, statuses, years_online, years_archive, action, active,
                                description, created_at, created_by)
select 'ACCESS_REQUEST', 'CANCELLED,REJECTED', 5, 15, 'REVIEW', true,
       'User access requests cancelled or rejected (kept with the access change log)', now(), 'SYSTEM'
where not exists (select 1 from nba_retention_rule where record_type = 'ACCESS_REQUEST');
