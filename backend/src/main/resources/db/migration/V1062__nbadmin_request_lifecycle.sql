-- Requests created before this release were submitted when they were created.
update nba_access_request set submitted_by = created_by, submitted_at = created_at;
update nba_access_request set applied_at = decided_at where status = 'APPROVED';

alter table nba_access_request drop constraint ck_nba_access_type;
alter table nba_access_request add constraint ck_nba_access_type
    check (request_type in ('CREATE_USER', 'MODIFY_ROLES', 'MODIFY_USER', 'DISABLE_USER', 'ENABLE_USER',
                            'MODIFY_ROLE_PERMISSIONS', 'CREATE_ROLE', 'DEACTIVATE_ROLE', 'REACTIVATE_ROLE'));

alter table nba_access_request drop constraint ck_nba_access_status;
alter table nba_access_request add constraint ck_nba_access_status
    check (status in ('DRAFT', 'PENDING', 'PENDING_SECOND', 'RETURNED', 'CANCELLED', 'REJECTED',
                      'APPROVED', 'SCHEDULED', 'FOR_IMPLEMENTATION', 'IMPLEMENTED'));

-- A decided request names its (last) decider.
alter table nba_access_request drop constraint ck_nba_access_decided;
alter table nba_access_request add constraint ck_nba_access_decided
    check (status in ('DRAFT', 'PENDING', 'PENDING_SECOND', 'CANCELLED')
        or (decided_by is not null and decided_at is not null));

-- A user request names the user; a group-profile request names the role (the permissions of a
-- change are checked on submission, a draft may still be incomplete).
alter table nba_access_request drop constraint ck_nba_access_subject;
alter table nba_access_request add constraint ck_nba_access_subject
    check ((request_type in ('MODIFY_ROLE_PERMISSIONS', 'CREATE_ROLE', 'DEACTIVATE_ROLE', 'REACTIVATE_ROLE')
            and role_code is not null)
        or (request_type not in ('MODIFY_ROLE_PERMISSIONS', 'CREATE_ROLE', 'DEACTIVATE_ROLE', 'REACTIVATE_ROLE')
            and username is not null));

-- External (portal) users: create, disable and enable only, with the party (decision D7).
alter table nba_access_request add constraint ck_nba_access_user_type
    check (user_type = 'INTERNAL'
        or (user_type = 'EXTERNAL'
            and request_type in ('CREATE_USER', 'DISABLE_USER', 'ENABLE_USER')
            and party_kind in ('INSURER', 'CLIENT') and party_code is not null));
alter table nba_access_request add constraint ck_nba_access_privilege
    check (privilege_level is null or privilege_level in ('LOW', 'STANDARD', 'HIGH', 'ADMIN'));
alter table nba_access_request add constraint ck_nba_access_cancelled
    check (status <> 'CANCELLED' or (cancel_reason is not null and cancelled_by is not null));

create index ix_nba_access_assigned on nba_access_request (lower(assigned_approver), status)
    where assigned_approver is not null;
create index ix_nba_access_creator on nba_access_request (lower(created_by), status);
create index ix_nba_access_batch on nba_access_request (batch_id) where batch_id is not null;
create index ix_nba_access_scheduled on nba_access_request (effective_from) where status = 'SCHEDULED';

-- ---------- Approvers in order (BRD 3.002.x "approver/s"; user requests have one) -------------
create table nba_access_request_approver (
    id          bigint generated by default as identity primary key,
    version     bigint        not null default 0,
    request_id  bigint        not null references nba_access_request (id),
    sequence    integer       not null,
    approver    varchar(50)   not null,
    decision    varchar(10)   not null default 'PENDING',
    remarks     varchar(1000),
    decided_at  timestamptz,
    created_at  timestamptz   not null,
    created_by  varchar(50)   not null,
    updated_at  timestamptz,
    updated_by  varchar(50),
    -- Deferred: a resubmission replaces the approver list in one transaction. An approver appears
    -- once per request (checked by the service, message "<user> is already an approver").
    constraint uq_nba_access_approver_seq unique (request_id, sequence) deferrable initially deferred,
    constraint ck_nba_access_approver_decision check (decision in ('PENDING', 'APPROVED', 'REJECTED', 'RETURNED')),
    constraint ck_nba_access_approver_seq check (sequence > 0)
);
create index ix_nba_access_approver_user on nba_access_request_approver (lower(approver), decision);

-- ---------- Request history (insert-only; every remark of the BRD) ----------------------------
create table nba_access_request_event (
    id           bigint generated by default as identity primary key,
    request_id   bigint        not null references nba_access_request (id),
    action       varchar(20)   not null,
    from_status  varchar(20),
    to_status    varchar(20)   not null,
    remarks      varchar(1000),
    actor        varchar(50)   not null,
    occurred_at  timestamptz   not null,
    constraint ck_nba_access_event_action check (action in ('SAVE', 'EDIT', 'SUBMIT', 'RESUBMIT', 'RETURN',
        'CANCEL', 'APPROVE', 'SECOND_APPROVE', 'REJECT', 'SCHEDULE', 'APPLY', 'APPLY_FAILED',
        'FOR_IMPLEMENTATION', 'IMPLEMENT'))
);
create index ix_nba_access_event_request on nba_access_request_event (request_id, occurred_at);

create function nba_access_request_event_immutable() returns trigger language plpgsql as $$
begin
    raise exception 'nba_access_request_event rows are immutable; the request history is insert-only';
end;
$$;

create trigger trg_nba_access_request_event_immutable
    before update or delete on nba_access_request_event
    for each row execute function nba_access_request_event_immutable();

create trigger trg_nba_access_request_event_no_truncate
    before truncate on nba_access_request_event
    for each statement execute function nba_access_request_event_immutable();

-- History of the requests created before this release: their submission and decision.
insert into nba_access_request_event (request_id, action, from_status, to_status, remarks, actor, occurred_at)
select id, 'SUBMIT', null, 'PENDING', justification, created_by, created_at from nba_access_request;
insert into nba_access_request_event (request_id, action, from_status, to_status, remarks, actor, occurred_at)
select id, case status when 'APPROVED' then 'APPROVE' when 'REJECTED' then 'REJECT' else 'RETURN' end,
       'PENDING', status, decision_comment, decided_by, decided_at
from nba_access_request where status in ('APPROVED', 'REJECTED', 'RETURNED');

