-- =====================================================================================
-- iNXT BrokerVerse - V1062 User Access Maintenance (BRD-11) request lifecycle (wave U1-A).
--   Requirements: docs/requirements/BDOI_UAM_BRD_SPEC.md
--     BRD 1.002-1.005    enrol / modify / deactivate / reactivate a user: drafts, user data
--                        (Windows ID, business unit, user level), reason, unlock
--     BRD 1.002.1.1.3    the requester chooses the approver (assigned_approver, approver rows)
--     BRD 1.006-1.008    correction of a returned request, cancellation with a reason, history
--     BRD 1.009          bulk requests: a batch of line requests (nba_access_request_batch)
--     BRD 2.002          approve, reject, return; four eyes (requester and subject user excluded)
--     BRD 3.002.1-4      group-profile requests CREATE_ROLE / MODIFY_ROLE_PERMISSIONS /
--                        DEACTIVATE_ROLE / REACTIVATE_ROLE with approvers in order, then the
--                        System Administrator implements them (FOR_IMPLEMENTATION -> IMPLEMENTED)
--     UAM-NFR-14         effective date: approved requests SCHEDULED until the daily job applies them
--     UAM-NFR-40         risk flags (PRIVILEGE_INCREASE, OUTSIDE_HOURS) and second approval
--     Decision D7        user type EXTERNAL (portal users of insurers and clients) through the
--                        port ExternalUserProvisioner; change log subject type EXTERNAL_USER
--   Design: docs/architecture/USER_ACCESS_DESIGN.md sections 3, 4.2-4.4 and 9.
--   Behaviour switches (the implement-request flow is live with this wave):
--     UAM_DIRECT_ROLE_EDIT       = false: roles change only by implementing an approved request
--                                  (PQ17); the emergency path stays audited and alerted.
--     UAM_ROLE_APPLY_ON_APPROVAL = false: approved group-profile and role-permission requests
--                                  wait for the System Administrator (BRD-11 p.6; UQ03).
-- =====================================================================================

-- ---------- Bulk batches (BRD 1.009) ---------------------------------------------------------
create table nba_access_request_batch (
    id          bigint generated by default as identity primary key,
    version     bigint        not null default 0,
    batch_no    varchar(30)   not null unique,
    file_name   varchar(255),
    lines       integer       not null default 0,
    status      varchar(20)   not null default 'DRAFT',
    remarks     varchar(1000),
    created_at  timestamptz   not null,
    created_by  varchar(50)   not null,
    updated_at  timestamptz,
    updated_by  varchar(50),
    constraint ck_nba_access_batch_status check (status in ('DRAFT', 'PENDING', 'RETURNED',
        'CANCELLED', 'REJECTED', 'APPROVED', 'PARTIAL'))
);

