-- iNXT BrokerVerse - V1100 Document storage foundation (build step ST0).
--   Decision: docs/architecture/DOCUMENT_STORAGE_DECISION.md (option C approved by BDOI,
--   26-Sep-2026): file content in S3, metadata in PostgreSQL, short-lived presigned links.
--     stored_file              metadata of every stored object (section 3 "Metadata") with the
--                              malware scan status (decision 2), the legal hold (decision 3) and
--                              the ECM reference (decision 5)
--     sto_record_class         parameterised record classes: bucket class, retention (mapped to
--                              the retention rules nba_retention_rule), under legal hold, archive
--                              to ECM
--     sto_legal_hold_request   place / release of a legal hold as a controlled action with
--                              requester, approver and reason (decision 3, DOA)
--   Module tables keep their bytea columns until ST1 moves them (per-table plan in the decision
--   document, "As built").
--   Runs after V790 (nba_retention_rule) and V1 (org_company) on a fresh database.
