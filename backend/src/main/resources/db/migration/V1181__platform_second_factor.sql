-- The system administrators request resets; the approvers of the security settings approve them.
insert into sec_role_permission (role_id, permission)
select r.id, 'MFA_RESET'
from sec_role r
where r.code = 'SYSADMIN'
  and not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = 'MFA_RESET');

insert into sec_role_permission (role_id, permission)
select distinct holder.role_id, 'MFA_RESET_APPROVE'
from sec_role_permission holder
where holder.permission = 'SECURITY_PARAMETER_APPROVE'
  and not exists (select 1 from sec_role_permission x where x.role_id = holder.role_id and x.permission = 'MFA_RESET_APPROVE');
