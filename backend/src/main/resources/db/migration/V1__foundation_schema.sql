-- ---------- Security ----------------------------------------------------------------
create table sec_role (
    id          bigint generated by default as identity primary key,
    version     bigint       not null default 0,
    code        varchar(40)  not null unique,
    name        varchar(120) not null,
    created_at  timestamptz  not null,
    created_by  varchar(50)  not null,
    updated_at  timestamptz,
    updated_by  varchar(50)
);

create table sec_role_permission (
    role_id    bigint      not null references sec_role (id),
    permission varchar(50) not null,
    primary key (role_id, permission)
);

create table sec_user (
    id                  bigint generated by default as identity primary key,
    version             bigint       not null default 0,
    username            varchar(50)  not null unique,
    full_name           varchar(120) not null,
    email               varchar(120),
    password_hash       varchar(100) not null,
    enabled             boolean      not null default true,
    locked              boolean      not null default false,
    failed_attempts     integer      not null default 0,
    last_login_at       timestamptz,
    home_branch_id      bigint,
    authorization_limit numeric(19, 2),
    created_at          timestamptz  not null,
    created_by          varchar(50)  not null,
    updated_at          timestamptz,
    updated_by          varchar(50)
);

create table sec_user_role (
    user_id bigint not null references sec_user (id),
    role_id bigint not null references sec_role (id),
    primary key (user_id, role_id)
);

-- ---------- Audit trail (insert only) -------------------------------------------------
create table audit_log (
    id          bigint generated by default as identity primary key,
    occurred_at timestamptz  not null,
    username    varchar(50)  not null,
    entity_type varchar(60)  not null,
    entity_id   varchar(60),
    action      varchar(30)  not null,
    summary     varchar(500) not null
);
create index ix_audit_time on audit_log (occurred_at);
create index ix_audit_entity on audit_log (entity_type, entity_id);
create index ix_audit_user on audit_log (lower(username), occurred_at);

-- ---------- Document numbering ------------------------------------------------------
create table document_sequence (
    sequence_key varchar(60) primary key,
    next_value   bigint      not null
);

-- ---------- Organisation --------------------------------------------------------------
create table org_company (
    id                        bigint generated by default as identity primary key,
    version                   bigint       not null default 0,
    code                      varchar(10)  not null unique,
    name                      varchar(150) not null,
    base_currency             varchar(3)    not null,
    tax_id                    varchar(30),
    address                   varchar(300),
    fiscal_year_start_month   integer      not null default 1 check (fiscal_year_start_month between 1 and 12),
    back_value_days           integer      not null default 0,
    forward_value_days        integer      not null default 0,
    retained_earnings_account varchar(30),
    record_status             varchar(30)  not null,
