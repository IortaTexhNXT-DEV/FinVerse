-- ---------- Financial periods ---------------------------------------------------------
create table per_fiscal_year (
    id         bigint generated by default as identity primary key,
    version    bigint      not null default 0,
    company_id bigint      not null references org_company (id),
    year_code  integer     not null,
    start_date date        not null,
    end_date   date        not null,
    status     varchar(10) not null,
    closed_by  varchar(50),
    closed_at  timestamptz,
    created_at timestamptz not null,
    created_by varchar(50) not null,
    updated_at timestamptz,
    updated_by varchar(50),
    constraint uq_fiscal_year unique (company_id, year_code),
    constraint ck_fy_dates check (end_date > start_date)
);

create table per_period (
    id                bigint generated by default as identity primary key,
    version           bigint       not null default 0,
    fiscal_year_id    bigint       not null references per_fiscal_year (id),
    company_id        bigint       not null references org_company (id),
    period_no         integer      not null,
    name              varchar(20)  not null,
    start_date        date         not null,
    end_date          date         not null,
    status            varchar(10)  not null,
    status_changed_by varchar(50),
    status_changed_at timestamptz,
    status_reason     varchar(200),
    created_at        timestamptz  not null,
    created_by        varchar(50)  not null,
    updated_at        timestamptz,
    updated_by        varchar(50),
    constraint uq_period unique (fiscal_year_id, period_no)
);
create index ix_period_dates on per_period (company_id, start_date, end_date);

-- ---------- Journals ------------------------------------------------------------------------
create table jnl_batch (
    id               bigint generated by default as identity primary key,
    version          bigint         not null default 0,
    company_id       bigint         not null references org_company (id),
    branch_id        bigint         not null references org_branch (id),
    batch_no         varchar(40)    not null,
    journal_type     varchar(20)    not null,
    status           varchar(20)    not null,
    transaction_date date           not null,
    value_date       date           not null,
    period_id        bigint references per_period (id),
    currency         varchar(3)      not null,
    narration        varchar(500)   not null,
    reference        varchar(60),
    source_module    varchar(30),
    source_reference varchar(80),
    reversal_of_id   bigint references jnl_batch (id),
    reversed_by_id   bigint references jnl_batch (id),
    total_debit      numeric(19, 2) not null,
    total_credit     numeric(19, 2) not null,
    submitted_by     varchar(50),
    submitted_at     timestamptz,
    authorized_by    varchar(50),
    authorized_at    timestamptz,
    rejected_by      varchar(50),
    rejection_reason varchar(200),
    posted_at        timestamptz,
    created_at       timestamptz    not null,
    created_by       varchar(50)    not null,
    updated_at       timestamptz,
    updated_by       varchar(50),
    constraint uq_batch_no unique (company_id, batch_no)
);
create index ix_batch_status on jnl_batch (company_id, status, value_date);
create index ix_batch_source on jnl_batch (company_id, source_module, source_reference);

create table jnl_line (
    id            bigint generated by default as identity primary key,
    batch_id      bigint         not null references jnl_batch (id),
    line_no       integer        not null,
    account_id    bigint         not null references coa_account (id),
    branch_id     bigint         not null references org_branch (id),
    side          varchar(6)     not null check (side in ('DEBIT', 'CREDIT')),
    currency      varchar(3)      not null,
    amount        numeric(19, 2) not null check (amount > 0),
    exchange_rate numeric(19, 8) not null,
    base_amount   numeric(19, 2) not null,
    cost_center   varchar(20),
    business_line varchar(20),
    party_code    varchar(30),
    reference     varchar(60),
    narration     varchar(250),
    constraint uq_line unique (batch_id, line_no)
);

-- ---------- General ledger (book of record) ---------------------------------------------
create table gl_ledger_entry (
    id            bigint generated by default as identity primary key,
    company_id    bigint         not null references org_company (id),
    branch_id     bigint         not null references org_branch (id),
    account_id    bigint         not null references coa_account (id),
    period_id     bigint         not null references per_period (id),
    value_date    date           not null,
    batch_id      bigint         not null references jnl_batch (id),
    batch_no      varchar(40)    not null,
    line_no       integer        not null,
    journal_type  varchar(20)    not null,
    currency      varchar(3)      not null,
    debit_fc      numeric(19, 2) not null,
    credit_fc     numeric(19, 2) not null,
    debit_base    numeric(19, 2) not null,
    credit_base   numeric(19, 2) not null,
    cost_center   varchar(20),
    business_line varchar(20),
    party_code    varchar(30),
    reference     varchar(60),
    narration     varchar(250),
    posted_at     timestamptz    not null,
    posted_by     varchar(50)    not null,
    constraint uq_ledger_line unique (batch_id, line_no)
);
create index ix_ledger_account_date on gl_ledger_entry (company_id, account_id, value_date);
create index ix_ledger_party on gl_ledger_entry (company_id, party_code) where party_code is not null;
create index ix_ledger_reference on gl_ledger_entry (company_id, reference) where reference is not null;

-- Posted ledger rows are immutable: block UPDATE and DELETE at database level.
create function gl_ledger_entry_immutable() returns trigger language plpgsql as $$
begin
    raise exception 'gl_ledger_entry rows are immutable; post a reversal instead';
end;
$$;
create trigger trg_ledger_immutable
    before update or delete on gl_ledger_entry
    for each row execute function gl_ledger_entry_immutable();

create table gl_daily_balance (
    company_id   bigint         not null,
    branch_id    bigint         not null,
    account_id   bigint         not null references coa_account (id),
    currency     varchar(3)      not null,
    balance_date date           not null,
    debit_fc     numeric(19, 2) not null,
    credit_fc    numeric(19, 2) not null,
    debit_base   numeric(19, 2) not null,
    credit_base  numeric(19, 2) not null,
    primary key (company_id, branch_id, account_id, currency, balance_date)
);
create index ix_daily_balance_date on gl_daily_balance (company_id, balance_date);
