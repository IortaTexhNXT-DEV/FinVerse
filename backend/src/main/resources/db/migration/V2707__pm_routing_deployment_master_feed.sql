-- =====================================================================================
-- Product Maintenance routing of BDOI's FRS, each kept selectable with the existing behaviour:
--   pm_request.source                 Source of a package request: Marketing, TSU or Insurer
--   pm_request.request_details        The Annex E fields of the request form not held elsewhere
--   pm_request.marketing_level        Marketing approvals given (Team Leader, Team Head, Unit Head)
--   pm_marketing_approval             History of the Marketing approvals of a request
--   pm_mancom_approval                ManCom approvers selected for a request and their decisions
--   MANCOM_APPROVED stage             ManCom approved; the deployment is requested by a button
--   pm_request.deployment_*           Package Deployment Request number, date and requestor
--   cat_product incentive and Annex A Incentive Eligible, Incentive Amount or Commission Rate,
--                                     Policy Type and Insured's Name of a Product Matrix record
--   pm_master_change                  Product master changes for the other BDOI systems, their
--                                     transfer file, status, attempts and errors
--   pm_master_sim_inbox               The receiving system of the product master changes in SIT/UAT
--   Settings: PM_MARKETING_CHAIN (ANY_ONE: one approval by the TL, TH or UH as BRPM.008 states;
--   TL_TH_UH: BDOI's chain, conflict C05), PM_MANCOM_ROUTING (SELECTED_PARALLEL_THEN_PRESIDENT:
--   BDOI's, conflict C17; ANY_MEMBER), PM_MANCOM_PRESIDENT, PM_DEPLOYMENT_REQUEST (AUTO: BRPM.015
--   forwards automatically; MANUAL: BDOI's button, conflict C20), PM_DIRECT_MAINTENANCE (true:
--   BDOI's direct maintenance with approval; false: packages only through package requests, C09).
-- =====================================================================================

alter table pm_request add column source varchar(20) not null default 'MARKETING';
alter table pm_request add constraint ck_pm_request_source
    check (source in ('MARKETING', 'TSU', 'INSURER'));
alter table pm_request add column request_details text;
alter table pm_request add column marketing_level integer not null default 0;
alter table pm_request add column deployment_no varchar(30);
alter table pm_request add column deployment_requested_at timestamptz;
alter table pm_request add column deployment_requested_by varchar(50);
alter table pm_request drop constraint ck_pm_request_status;
alter table pm_request add constraint ck_pm_request_status check (status in ('DRAFT',
    'FOR_MKT_APPROVAL', 'FOR_TSU_REVIEW', 'FOR_TSU_APPROVAL', 'NEGOTIATION', 'TERMS_REVIEW',
    'FOR_MKT_REVIEW', 'REQUIREMENTS_PREP', 'FOR_MANCOM', 'MANCOM_APPROVED', 'WITH_MBS',
    'FOR_VALIDATION', 'RELEASED', 'RETIRED', 'NOT_PROCEEDED', 'VOIDED'));

create table pm_marketing_approval (
    id          bigint generated by default as identity primary key,
    request_id  bigint        not null references pm_request (id),
    level_no    integer       not null,
    approver    varchar(50)   not null,
    decision    varchar(20)   not null,
    remarks     varchar(1000),
    decided_at  timestamptz   not null,
    constraint ck_pm_marketing_approval check (decision in ('APPROVED', 'RETURNED', 'REJECTED'))
);
create index ix_pm_marketing_approval on pm_marketing_approval (request_id, id);

create table pm_mancom_approval (
    id          bigint generated by default as identity primary key,
    version     bigint        not null default 0,
    request_id  bigint        not null references pm_request (id),
    round_no    integer       not null,
    approver    varchar(50)   not null,
    president   boolean       not null default false,
    status      varchar(20)   not null,
    remarks     varchar(1000),
    decided_at  timestamptz,
    created_at  timestamptz   not null,
    created_by  varchar(50)   not null,
    updated_at  timestamptz,
    updated_by  varchar(50),
    constraint ck_pm_mancom_approval check (status in ('WAITING', 'PENDING', 'APPROVED',
        'RETURNED', 'REJECTED', 'CLOSED'))
);
create index ix_pm_mancom_approval on pm_mancom_approval (request_id, round_no);
create index ix_pm_mancom_approver on pm_mancom_approval (lower(approver), status);

