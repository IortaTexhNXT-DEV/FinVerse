alter table cat_product add column incentive_eligible boolean not null default false;
alter table cat_product add column incentive_amount numeric(19, 2);
alter table cat_product add column incentive_rate numeric(9, 4);
alter table cat_product add column policy_type varchar(30);
alter table cat_product add column insured_name varchar(250);
alter table cat_product add constraint ck_cat_product_incentive check (
    (incentive_amount is null or incentive_amount > 0)
    and (incentive_rate is null or (incentive_rate > 0 and incentive_rate <= 100))
    and (not incentive_eligible or incentive_amount is not null or incentive_rate is not null));

create table pm_master_change (
    id                bigint generated by default as identity primary key,
    version           bigint        not null default 0,
    product_code      varchar(20)   not null,
    version_no        integer,
    change_kind       varchar(20)   not null,
    effective_date    date,
    source_request_no varchar(40),
    status            varchar(20)   not null,
    attempts          integer       not null default 0,
    file_name         varchar(120),
    sent_at           timestamptz,
    error             varchar(500),
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    updated_at        timestamptz,
    updated_by        varchar(50),
    constraint ck_pm_master_change check (status in ('PENDING', 'SENT', 'FAILED'))
);
create index ix_pm_master_change on pm_master_change (status, created_at);

create table pm_master_sim_inbox (
    id           bigint generated by default as identity primary key,
    file_name    varchar(120) not null,
    content      text         not null,
    record_count integer      not null,
    received_at  timestamptz  not null
);

