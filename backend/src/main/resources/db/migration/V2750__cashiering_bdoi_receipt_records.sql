-- Year of a receipt series and its number format (FRS.CSH.02.03.02 / 02.03.03; Appendix R, C4):
-- the format keeps the prefix, year and branch indicator of the series and the token {SEQ}; a
-- series without a format numbers as before (prefix and zero-filled sequence).
alter table csh_receipt_series add column if not exists series_year integer;
alter table csh_receipt_series add column if not exists number_format varchar(80);

-- Unapplied payment types of BDOI's FRS (FRS.CSH.06.01.03): AR Insurer Refund (cancellation or
-- reinstatement of a remitted AR), AP Unapplied Commission (reinstatement of an OR), Commission
-- Receivable payment (cancellation of an OR) and the unapplied payment of a reinstated AR.
alter table csh_unapplied drop constraint if exists ck_csh_unapplied_origin;
alter table csh_unapplied add constraint ck_csh_unapplied_origin check (origin in ('NO_MATCH', 'EXCESS',
    'CANCELLED_REFERENCE', 'ADJUSTMENT', 'CANCELLATION', 'DP_REINSTATE', 'REMITTANCE_RETURN', 'REAPPLY',
    'PREBOOKED', 'OTHER', 'MIGRATED', 'AR_INSURER_REFUND', 'AP_UNAPPLIED_COMMISSION',
    'COMMISSION_RECEIVABLE', 'REINSTATEMENT'));

