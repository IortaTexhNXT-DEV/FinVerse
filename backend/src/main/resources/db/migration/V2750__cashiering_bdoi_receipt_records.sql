-- =====================================================================================
-- iNXT BrokerVerse - V2750 Cashiering: BDOI's creation, cancellation and reinstatement records
-- (Operations Cashiering FRS v3.2: FRS.CSH.02.01, 02.02, 02.05, 03.01, 04.01).
--   csh_receipt_record          one record per AR / OR to create, cancel or reinstate, numbered
--                               <Prefix>-<Receipt Type>-<Sequence> (CR-AR, CR-OR, CN-AR, CN-OR,
--                               RE-AR, RE-OR), with the statuses Created, For Posting, Returned,
--                               posted (AR/OR Issued, Cancelled or Reinstated) and Record Cancelled
--   csh_receipt_record_account  the accounts of a record with the amount of each
--   csh_bank_account            the maintained list "Post to Bank Account" with its currency,
--                               default per currency and GL account
--   sys_parameter               the settings that carry the points BDOI decides (Appendix R)
-- =====================================================================================

create table csh_receipt_record (
    id                 bigint generated by default as identity primary key,
    version            bigint         not null default 0,
    company_id         bigint         not null references org_company (id),
    record_no          varchar(40)    not null,
    record_kind        varchar(15)    not null
        check (record_kind in ('CREATION', 'CANCELLATION', 'REINSTATEMENT')),
    receipt_kind       varchar(2)     not null check (receipt_kind in ('AR', 'OR')),
    receipt_type       varchar(30)    not null,
    stage              varchar(20)    not null
        check (stage in ('CREATED', 'FOR_POSTING', 'RETURNED', 'POSTED', 'RECORD_CANCELLED')),
    branch_id          bigint         references org_branch (id),
    entry_type         varchar(10)    check (entry_type in ('CLIENT', 'INSURER', 'OTHER')),
    client_code        varchar(30),
    client_name        varchar(250),
    insurer_code       varchar(30),
    insurer_name       varchar(250),
    insurer_bank       varchar(100),
    payor_name         varchar(250),
    tender_type        varchar(20)    check (tender_type in ('CASH', 'CHECK', 'DIRECT_CREDIT')),
    currency           varchar(3),
    bank_account       varchar(40),
    amount             numeric(19, 2),
    vat                numeric(19, 2),
    wtax               numeric(19, 2),
    certificate_ref    varchar(60),
    check_no           varchar(40),
    check_date         date,
    check_bank         varchar(60),
    receipt_date       date,
    remarks            varchar(250),
    other_income_ref   varchar(60),
    receipt_id         bigint         references csh_receipt (id),
    receipt_no         varchar(40),
    reason_code        varchar(40),
    reason_text        varchar(250),
    reinstatement_type varchar(10)    check (reinstatement_type in ('FULL', 'PARTIAL')),
    invoice_no         varchar(40),
    account_officer    varchar(100),
    unit_head          varchar(100),
    team_leader        varchar(100),
    return_reason      varchar(250),
    submitted_by       varchar(50),
    submitted_at       timestamptz,
    posted_by          varchar(50),
    posted_at          timestamptz,
    posting_result     varchar(500),
    journal_batch_no   varchar(40),
    created_at         timestamptz    not null,
    created_by         varchar(50)    not null,
    updated_at         timestamptz,
    updated_by         varchar(50),
    constraint uq_csh_receipt_record unique (company_id, record_no)
);
create index ix_csh_receipt_record_stage on csh_receipt_record (company_id, record_kind, stage);
create index ix_csh_receipt_record_receipt on csh_receipt_record (receipt_id);

create table csh_receipt_record_account (
    record_id   bigint         not null references csh_receipt_record (id),
    line_no     integer        not null,
    reference   varchar(60)    not null,
    amount      numeric(19, 2) not null,
    primary key (record_id, line_no)
);

create table csh_bank_account (
    id                   bigint generated by default as identity primary key,
    version              bigint        not null default 0,
    company_id           bigint        not null references org_company (id),
    code                 varchar(40)   not null,
    name                 varchar(120)  not null,
    currency             varchar(3)    not null,
    gl_account_code      varchar(30),
    default_for_currency boolean       not null default false,
    active               boolean       not null default true,
    created_at           timestamptz   not null,
    created_by           varchar(50)   not null,
    updated_at           timestamptz,
    updated_by           varchar(50),
    constraint uq_csh_bank_account unique (company_id, code)
);

-- BDOI's list of FRS.CSH.02.01.02 / 02.02.02 for every company (the GL account is set by
-- Comptrollership; without it the collection account parameter applies).
insert into csh_bank_account (company_id, code, name, currency, default_for_currency, created_at,
                              created_by)
select c.id, v.code, v.name, v.currency, v.dflt, now(), 'SYSTEM'
from org_company c
cross join (values
    ('DFLB_CURRENT_ORTIGAS', 'DFLB - Current (BDO Ortigas)', 'PHP', false),
    ('DFLB_SAVINGS_ORTIGAS', 'DFLB Savings (BDO Ortigas)', 'PHP', true),
    ('DFLB_SAVINGS_MALL', 'DFLB Savings Mall (Peso)', 'PHP', false),
    ('DFLB_SAVINGS_TRADE', 'DFLB Savings Trade (Peso)', 'PHP', false),
    ('DFLB_SAVINGS_FX', 'DFLB Savings FX (BDO Ortigas)', 'USD', true)
) as v(code, name, currency, dflt)
on conflict (company_id, code) do nothing;

