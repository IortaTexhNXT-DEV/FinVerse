-- =====================================================================================
-- Cashiering: the AR and OR forms and the printing of receipts (FRS.CSH.02.04, 02.06).
--   csh_receipt_form            versions of the AR and OR forms (header, body notes, footer lines),
--                               effective from a date once another authorised user approves them
--   csh_receipt                 certificate number given at the first print (C4)
--   csh_print_batch / _line     copy printed, ZIP of the receipts, reprint mark, skipped receipts
--   csh_certificate_of_payment  series number of the Certification of Payment
-- =====================================================================================

create table csh_receipt_form (
    id                  bigint generated by default as identity primary key,
    version             bigint        not null default 0,
    company_id          bigint        not null references org_company (id),
    form_kind           varchar(2)    not null check (form_kind in ('AR', 'OR')),
    version_no          integer       not null,
    company_name        varchar(150),
    company_description varchar(200),
    company_address     varchar(300),
    company_vat         varchar(40),
    note_line           varchar(500),
    footer_1            varchar(500),
    footer_2            varchar(500),
    footer_3            varchar(500),
    footer_4            varchar(500),
    effective_from      date          not null,
    status              varchar(20)   not null
        check (status in ('PENDING_APPROVAL', 'APPROVED', 'REJECTED')),
    decided_by          varchar(50),
    decided_at          timestamp with time zone,
    decision_remarks    varchar(250),
    created_at          timestamp with time zone not null default now(),
    created_by          varchar(50)   not null,
    updated_at          timestamp with time zone,
    updated_by          varchar(50),
    constraint uq_csh_receipt_form unique (company_id, form_kind, version_no)
);

