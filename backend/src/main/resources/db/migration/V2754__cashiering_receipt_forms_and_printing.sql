alter table csh_receipt add column certificate_no varchar(40);
alter table csh_receipt add column certificate_date date;
create unique index uq_csh_receipt_certificate on csh_receipt (certificate_no)
    where certificate_no is not null;

alter table csh_print_batch add column copy_label varchar(10) not null default 'CLIENT'
    check (copy_label in ('CLIENT', 'COMPANY', 'BOTH'));
