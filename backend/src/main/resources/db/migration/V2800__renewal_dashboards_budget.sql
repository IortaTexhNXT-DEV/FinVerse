-- Renewal dashboards and the Annual Renewal Budget (BDOI Renewal FRS v1.1, FRRN.002.02, FRRN.003,
-- FRRN.042): the renewal budget by fiscal year, segment and hierarchy with its monthly new, renewal
-- and organic amounts and its history; the processing assignment of the placement processor; the
-- parameters of the dashboards; the functions of the budget, KYC, RMU, audit log and billing
-- screens of the Renewal module and their grants.

-- ---------- Annual Renewal Budget (FRRN.042.02) ----------------------------------------------------
create table rnw_budget (
    id              bigint generated by default as identity primary key,
    version         bigint        not null default 0,
    company_id      bigint        not null references org_company (id),
    fiscal_year     integer       not null check (fiscal_year between 2000 and 2100),
    measure         varchar(20)   not null default 'PREMIUM',
    segment         varchar(40)   not null,
    region          varchar(40),
    team            varchar(40),
    sub_team        varchar(40),
    unit_head       varchar(50),
    section_head    varchar(50),
    team_head       varchar(50),
    team_lead       varchar(50),
    account_officer varchar(50),
    natural_key     varchar(400)  not null,
    created_at      timestamptz   not null,
    created_by      varchar(50)   not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint ck_rnw_budget_measure check (measure in ('PREMIUM', 'COMMISSION')),
    constraint uq_rnw_budget_key unique (company_id, natural_key)
);
create index ix_rnw_budget_year on rnw_budget (company_id, fiscal_year, segment);

create table rnw_budget_month (
    budget_id      bigint         not null references rnw_budget (id),
    month_no       integer        not null check (month_no between 1 and 12),
    new_amount     numeric(19, 2) not null default 0 check (new_amount >= 0),
    renewal_amount numeric(19, 2) not null default 0 check (renewal_amount >= 0),
    organic_amount numeric(19, 2) not null default 0 check (organic_amount >= 0),
    primary key (budget_id, month_no)
);

-- Insert-only history of the budget amounts (FRRN.042.06).
create table rnw_budget_history (
    id          bigint generated by default as identity primary key,
    budget_id   bigint         not null references rnw_budget (id),
    field       varchar(60)    not null,
    previous    numeric(19, 2),
    updated     numeric(19, 2),
    modified_by varchar(50)    not null,
    modified_at timestamptz    not null
);
create index ix_rnw_budget_history on rnw_budget_history (budget_id, id);

-- ---------- Placement processor of an account (FRRN.003.02.01) --------------------------------------
-- New Business and renewal accounts in the processing dashboard: the Placement Processor assigned to
-- an account submitted for placement (Assigned and Unassigned tabs).
create table rnw_processing_assignment (
    id          bigint generated by default as identity primary key,
    version     bigint       not null default 0,
    company_id  bigint       not null references org_company (id),
    arn         varchar(40)  not null,
    processor   varchar(50)  not null,
    created_at  timestamptz  not null,
    created_by  varchar(50)  not null,
    updated_at  timestamptz,
    updated_by  varchar(50),
    constraint uq_rnw_processing_assignment unique (company_id, arn)
);

-- Placement and policy tracking of an account (FRRN.003.02.03/.04, FRRN.29.05, FRRN.033.04): the
-- policy status, the placement issue and its resolution date, and the transmittal of the policy to
-- the client with the reason of an unsuccessful sending.
create table rnw_placement_tracking (
    id                  bigint generated by default as identity primary key,
    version             bigint        not null default 0,
    company_id          bigint        not null references org_company (id),
    arn                 varchar(40)   not null,
    policy_status       varchar(20),
    with_issue          boolean       not null default false,
    placement_issue     varchar(500),
    resolution_date     date,
    transmittal_status  varchar(20),
    transmittal_reason  varchar(500),
    transmitted_at      timestamptz,
    created_at          timestamptz   not null,
    created_by          varchar(50)   not null,
    updated_at          timestamptz,
    updated_by          varchar(50),
    constraint uq_rnw_placement_tracking unique (company_id, arn),
    constraint ck_rnw_placement_tracking_policy check (policy_status is null
        or policy_status in ('PENDING', 'RECEIVED', 'SPOILED', 'CANCELED', 'WITH_ISSUE')),
    constraint ck_rnw_placement_tracking_transmittal check (transmittal_status is null
        or transmittal_status in ('SENT', 'PENDING', 'UNSUCCESSFUL'))
);

