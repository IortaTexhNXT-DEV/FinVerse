insert into sec_permission_action (permission, area, action)
values ('RNW_BUDGET', 'RENEWAL', 'AMEND'),
       ('RNW_KYC', 'RENEWAL', 'AMEND'),
       ('RNW_RMU_MAINTAIN', 'RENEWAL', 'AMEND'),
       ('RNW_AUDIT_VIEW', 'RENEWAL', 'VIEW'),
       ('RNW_BILLING', 'RENEWAL', 'CREATE')
on conflict do nothing;

insert into sec_role_permission (role_id, permission)
select r.id, g.permission
from sec_role r
join (values
    ('BUSINESS_ADMIN', 'RNW_BUDGET'), ('BUSINESS_ADMIN', 'RNW_RMU_MAINTAIN'),
    ('BUSINESS_ADMIN', 'RNW_AUDIT_VIEW'),
    ('MKT_TL', 'RNW_KYC'), ('MKT_AO', 'RNW_KYC'), ('MKT_TL', 'RNW_AUDIT_VIEW'),
    ('PROCESSING_TL', 'RNW_BILLING'), ('PROCESSOR', 'RNW_BILLING'), ('PROCESSOR', 'RNW_EXPORT'),
    ('PROCESSING_TL', 'RNW_AUDIT_VIEW'), ('AUDITOR', 'RNW_AUDIT_VIEW')
) as g(role_code, permission) on g.role_code = r.code
where not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = g.permission);

