-- Each record of an insurer disposition file, matched to its renewal account.
create table rnw_insurer_disposition_line (
    id                bigint generated by default as identity primary key,
    company_id        bigint        not null references org_company (id),
    job_no            varchar(40)   not null,
    row_no            integer       not null,
    candidate_id      bigint        references rnw_candidate (id),
    disposition_code  varchar(40),
    insurer_code      varchar(40),
    insurer_branch    varchar(120),
    insurer_remarks   varchar(1000),
    matched_on        varchar(40),
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null
);
create index ix_rnw_insurer_disposition_line_candidate on rnw_insurer_disposition_line (candidate_id);

