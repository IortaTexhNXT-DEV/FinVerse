-- Insurer dispositions of BDOI's Renewal FRS (FRRN.013.02): the nine values of the insurer's
-- approval in the insurer disposition file, each mapped to one of the three insurer responses of
-- the BRD and to BDOI's bucket and renewal disposition.

create table rnw_insurer_disposition_map (
    code          varchar(40)  primary key,
    label         varchar(120) not null,
    outcome       varchar(20)  not null,
    brd_response  varchar(20)  not null,
    bucket        varchar(20)  not null,
    disposition   varchar(30)  not null,
    sort_order    integer      not null,
    active        boolean      not null default true,
    constraint ck_rnw_insurer_disposition_outcome check (outcome in ('RENEW', 'REVIEW', 'NOT_RENEWED')),
    constraint ck_rnw_insurer_disposition_response check (brd_response in ('RENEW_AS_IS', 'REVISE', 'REJECT'))
);

