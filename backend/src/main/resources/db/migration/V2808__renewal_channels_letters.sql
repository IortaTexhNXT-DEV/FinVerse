insert into sec_role_permission (role_id, permission)
select r.id, g.permission
from sec_role r
join (values
    ('BUSINESS_ADMIN', 'RNW_CHANNEL_MONITOR'), ('BUSINESS_ADMIN', 'RNW_CHANNEL_SETUP'),
    ('SYSADMIN', 'RNW_CHANNEL_MONITOR'), ('SYSADMIN', 'RNW_CHANNEL_SETUP'),
    ('PROCESSING_TL', 'RNW_CHANNEL_MONITOR'), ('PROCESSOR', 'RNW_CHANNEL_MONITOR'),
    ('MKT_TL', 'RNW_CHANNEL_MONITOR')
) as g(role_code, permission) on g.role_code = r.code
where not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = g.permission);

