-- Delivery channels and client letters of BDOI's Renewal FRS (FRRN.017.02, FRRN.022 to FRRN.024,
-- FRRN.032.02, FRRN.033.04, Annex M): the outbound messages to CCM (client documents) and MFT
-- (insurer files) with their delivery status history, the connection settings of each channel
-- (simulator for SIT and UAT until BDOI IT gives the connection details), the automatic Renewal
-- Advice notice, BDOI's file names, the password convention of protected files and the offsets of
-- the closing letters.

create table rnw_channel_message (
    id                bigint generated by default as identity primary key,
    version           bigint        not null default 0,
    company_id        bigint        not null references org_company (id),
    message_no        varchar(30)   not null,
    channel           varchar(10)   not null,
    direction         varchar(10)   not null,
    doc_kind          varchar(30)   not null,
    doc_ref           varchar(60),
    candidate_id      bigint        references rnw_candidate (id),
    renewal_ref       varchar(30),
    file_name         varchar(255),
    attachment_id     bigint,
    recipients_to     varchar(1000),
    recipients_cc     varchar(1000),
    subject           varchar(300),
    body              text,
    client_id         bigint,
    status            varchar(30)   not null,
    external_ref      varchar(80),
    attempts          integer       not null default 0,
    last_error        varchar(1000),
    submitted_at      timestamptz,
    sent_at           timestamptz,
    delivered_at      timestamptz,
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    updated_at        timestamptz,
    updated_by        varchar(50),
    constraint uq_rnw_channel_message_no unique (company_id, message_no),
    constraint ck_rnw_channel_message_channel check (channel in ('CCM', 'MFT', 'EMAIL')),
    constraint ck_rnw_channel_message_direction check (direction in ('OUTBOUND', 'INBOUND')),
    constraint ck_rnw_channel_message_status check (status in ('PENDING_TRANSMISSION', 'SUBMITTED',
        'SENT', 'DELIVERED', 'FAILED', 'CANCELLED', 'RECEIVED', 'PROCESSED'))
);
create index ix_rnw_channel_message_candidate on rnw_channel_message (candidate_id);
create index ix_rnw_channel_message_status on rnw_channel_message (company_id, channel, status);

create table rnw_channel_event (
    id                bigint generated by default as identity primary key,
    message_id        bigint        not null references rnw_channel_message (id),
    status            varchar(30)   not null,
    detail            varchar(1000),
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null
);
create index ix_rnw_channel_event_message on rnw_channel_event (message_id);

