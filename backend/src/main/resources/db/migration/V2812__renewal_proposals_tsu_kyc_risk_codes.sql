-- Proposals, TSU requests, KYC monitoring and risk code maintenance of BDOI's Renewal FRS
-- (FRRN.017, FRRN.018, FRRN.019, FRRN.038, FRRN.039).

create table rnw_proposal (
    id                bigint generated by default as identity primary key,
    version           bigint        not null default 0,
    company_id        bigint        not null references org_company (id),
    proposal_no       varchar(30)   not null,
    candidate_id      bigint        not null references rnw_candidate (id),
    kind              varchar(10)   not null,
    file_name         varchar(200)  not null,
    attachment_id     bigint,
    signatories       varchar(500),
    status            varchar(20)   not null,
    message_no        varchar(30),
    recipients        varchar(1000),
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    updated_at        timestamptz,
    updated_by        varchar(50),
    constraint uq_rnw_proposal_no unique (company_id, proposal_no),
    constraint ck_rnw_proposal_kind check (kind in ('QUICK', 'FULL', 'TSU')),
    constraint ck_rnw_proposal_status check (status in ('GENERATED', 'SENT'))
);
create index ix_rnw_proposal_candidate on rnw_proposal (candidate_id);

create table rnw_tsu_request (
    id                bigint generated by default as identity primary key,
    version           bigint        not null default 0,
    company_id        bigint        not null references org_company (id),
    request_no        varchar(30)   not null,
    candidate_id      bigint        not null references rnw_candidate (id),
    status            varchar(30)   not null,
    remarks           varchar(1000),
    decision_remarks  varchar(1000),
    decided_by        varchar(50),
    tsu_officer       varchar(50),
    proposal_attachment_id bigint,
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    updated_at        timestamptz,
    updated_by        varchar(50),
    constraint uq_rnw_tsu_request_no unique (company_id, request_no),
    constraint ck_rnw_tsu_request_status check (status in ('DRAFT', 'PENDING_TL_APPROVAL',
        'RETURNED_FOR_REVISION', 'REJECTED', 'APPROVED', 'FOR_TSU_PROCESSING', 'COMPLETED',
        'CANCELLED'))
);
create index ix_rnw_tsu_request_candidate on rnw_tsu_request (candidate_id);

create table rnw_tsu_quote (
    id                bigint generated by default as identity primary key,
    request_id        bigint        not null references rnw_tsu_request (id),
    insurer_code      varchar(30)   not null,
    premium           numeric(19, 2),
    terms             varchar(1000),
    selected          boolean       not null default false,
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    constraint uq_rnw_tsu_quote unique (request_id, insurer_code)
);

create table rnw_kyc_activity (
    id                bigint generated by default as identity primary key,
    company_id        bigint        not null references org_company (id),
    candidate_id      bigint        not null references rnw_candidate (id),
    status            varchar(30)   not null,
    activity          varchar(200),
    remarks           varchar(1000),
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    constraint ck_rnw_kyc_activity_status check (status in ('KYC_DUE', 'KYC_UPCOMING',
        'KYC_NOT_REQUIRED', 'PENDING_FOLLOW_UP', 'KYC_COMPLETED'))
);
create index ix_rnw_kyc_activity_candidate on rnw_kyc_activity (candidate_id, id);

alter table rnw_candidate add column kyc_status varchar(30);
alter table rnw_candidate add column kyc_review_due date;

alter table rnw_non_renewable_risk_code add column renewable boolean not null default false;
alter table rnw_non_renewable_risk_code add column description varchar(200);
alter table rnw_non_renewable_risk_code add column remarks varchar(500);

