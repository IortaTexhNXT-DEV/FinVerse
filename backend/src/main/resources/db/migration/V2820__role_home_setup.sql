-- =====================================================================================
-- iNXT BrokerVerse - V2820 Role Home Set-up (FR-CR-010, conformance gap G07).
--   sys_role_home   the home-page widgets of a role, in display order (codes of
--                   dashboard.domain.HomeWidget, comma separated). The System Administrator requests
--                   a new set with a reason; it applies when another user approves it (pending_*).
--                   A role without a row shows the delivered set of widgets.
-- Permissions: ROLE_HOME_MANAGE (system administrator, requests), ROLE_HOME_APPROVE (information
-- security officer, approves).
-- =====================================================================================

create table sys_role_home (
    id              bigint generated by default as identity primary key,
    version         bigint       not null default 0,
    role_code       varchar(40)  not null references sec_role (code),
    widgets         varchar(400),
    pending_widgets varchar(400),
    pending_reason  varchar(500),
    pending_by      varchar(50),
    pending_at      timestamptz,
    changed_reason  varchar(500),
    changed_by      varchar(50),
    changed_at      timestamptz,
    approved_by     varchar(50),
    created_at      timestamptz  not null,
    created_by      varchar(50)  not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint uq_sys_role_home_role unique (role_code),
    constraint ck_sys_role_home_pending check (
        (pending_widgets is null and pending_by is null and pending_at is null)
        or (pending_widgets is not null and pending_by is not null and pending_at is not null
            and pending_reason is not null))
);

insert into sec_permission_action (permission, area, action)
values ('ROLE_HOME_MANAGE', 'ADMINISTRATION', 'AMEND'),
       ('ROLE_HOME_APPROVE', 'ADMINISTRATION', 'APPROVE')
on conflict (permission, action) do nothing;

insert into sec_role_permission (role_id, permission)
select r.id, g.permission
from sec_role r
join (values ('SYSADMIN', 'ROLE_HOME_MANAGE'), ('INFOSEC_OFFICER', 'ROLE_HOME_APPROVE')) as g(role_code, permission)
  on g.role_code = r.code
where not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = g.permission);
