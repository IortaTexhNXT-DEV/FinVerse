-- =====================================================================================
-- iNXT BrokerVerse - V2821 Submitted Policies: Notification Recipients (FR-SP-082 R3, BRIDSP-28,
-- conformance gap G12).
--   sbm_notification_recipient  who is told of a lifecycle event of a submitted policy, per event
--                               type and segment (null = every segment): a role, a named user, the
--                               assigned handler or AO of the record, an outside e-mail address of
--                               the bank counterpart, or OFF (the event is not sent for the
--                               segment). Maker and checker (SBM_RULE_MAINTAIN, SBM_RULE_APPROVE).
-- An event type without an active recipient keeps telling the handler and the AO of the record.
-- =====================================================================================

create table sbm_notification_recipient (
    id              bigint generated by default as identity primary key,
    version         bigint        not null default 0,
    company_id      bigint        not null references org_company (id),
    event_code      varchar(40)   not null references msg_notification_event (code),
    segment         varchar(30),
    recipient_type  varchar(20)   not null
        check (recipient_type in ('ROLE', 'USER', 'HANDLER', 'AO', 'EMAIL', 'OFF')),
    recipient       varchar(120),
    description     varchar(250),
    record_status   varchar(30)   not null,
    authorized_by   varchar(50),
    authorized_at   timestamptz,
    created_at      timestamptz   not null,
    created_by      varchar(50)   not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint ck_sbm_notification_recipient_value check (
        (recipient_type in ('ROLE', 'USER', 'EMAIL')) = (recipient is not null))
);

create index ix_sbm_notification_recipient_company on sbm_notification_recipient (company_id, event_code);
create index ix_sbm_notification_recipient_event on sbm_notification_recipient (event_code);
