-- Daily reconciliation of the users with the UIDM-ISC / Enterprise SSO directory
-- (IdentityReconciliationJob): each mismatch found by a run, kept as evidence and listed on the
-- Identity Sync screen, and the notice to the user administrators.
create table idn_reconciliation_mismatch (
    id          bigint generated by default as identity primary key,
    run_date    date         not null,
    username    varchar(50)  not null,
    windows_id  varchar(50),
    kind        varchar(30)  not null,
    detail      varchar(500) not null,
    found_at    timestamptz  not null,
    constraint ck_idn_recon_kind check (kind in ('NOT_IN_DIRECTORY', 'STATUS', 'GROUP_PROFILES'))
);
create index ix_idn_recon_run on idn_reconciliation_mismatch (run_date desc, username);

insert into msg_notification_event (code, name, module, description, default_in_app, default_email, sort_order) values
    ('UAM_RECONCILIATION_MISMATCH', 'Identity reconciliation mismatch', 'USER_ACCESS',
     'The daily reconciliation found users that differ from the UIDM-ISC directory', true, true, 690);
