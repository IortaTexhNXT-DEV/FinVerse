-- Identity Sync monitoring on the User Access screens.
--   1. A refused provisioning event can be dismissed with a remark (idn_identity_event is
--      append-only, V2823, so the dismissal is a row of its own).
--   2. A reconciliation mismatch is resolved with a remark; who and when are kept.
--   3. UAM_RECONCILIATION_INTERVAL_DAYS: the reconciliation compares the users with the directory
--      every n days (1 = daily, 0 = never); the job keeps its daily time and skips the other days.

-- ---------- 1. Dismissed refused events -------------------------------------------------------------
create table idn_event_dismissal (
    id            bigint generated by default as identity primary key,
    event_id      bigint        not null,
    remark        varchar(500)  not null,
    dismissed_by  varchar(50)   not null,
    dismissed_at  timestamptz   not null,
    constraint fk_idn_dismissal_event foreign key (event_id) references idn_identity_event (id),
    constraint uq_idn_dismissal_event unique (event_id),
    constraint ck_idn_dismissal_remark check (length(trim(remark)) > 0)
);

-- ---------- 2. Resolved mismatches ----------------------------------------------------------------
alter table idn_reconciliation_mismatch add column resolved_by varchar(50);
alter table idn_reconciliation_mismatch add column resolved_at timestamptz;
alter table idn_reconciliation_mismatch add column resolution_remark varchar(500);
alter table idn_reconciliation_mismatch add constraint ck_idn_recon_resolved
    check ((resolved_at is null and resolved_by is null and resolution_remark is null)
        or (resolved_at is not null and resolved_by is not null and resolution_remark is not null));
create index ix_idn_recon_open on idn_reconciliation_mismatch (found_at desc) where resolved_at is null;

-- ---------- 3. Reconciliation interval -----------------------------------------------------------
insert into sys_parameter (param_key, param_value, value_type, category, description, min_value,
    max_value, created_at, created_by)
values ('UAM_RECONCILIATION_INTERVAL_DAYS', '1', 'INTEGER', 'SECURITY',
        'Days between two reconciliations of the users with the UIDM-ISC directory (1 = daily, 0 = never)',
        0, 31, now(), 'SYSTEM')
on conflict (param_key) do nothing;
