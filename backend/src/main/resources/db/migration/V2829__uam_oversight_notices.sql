-- Oversight of User Access by Information Security, and the notices of the UIDM-ISC model.
--   1. nba_sod_violation: each breach of an active separation-of-duties rule found by the daily
--      job UAM_SOD_VIOLATIONS (first found, and cleared when it no longer holds).
--   2. nba_certification_extract: who took a certification extract of the accounts, group profiles
--      and permissions, when, the format, the rows and the SHA-256 of the file.
--   3. Notices: a new breach of separation of duties and a certification extract taken go to
--      Information Security; the request notices now speak of group-profile changes (users are
--      maintained in UIDM-ISC) and the password expiry notice of local test accounts.

-- ---------- 1. Separation-of-duties breaches -------------------------------------------------------
create table nba_sod_violation (
    id          bigint generated by default as identity primary key,
    rule_code   varchar(30)  not null,
    username    varchar(50)  not null,
    found_at    timestamptz  not null,
    cleared_at  timestamptz,
    constraint ck_nba_sod_violation_cleared check (cleared_at is null or cleared_at >= found_at)
);
create unique index uq_nba_sod_violation_open on nba_sod_violation (rule_code, username)
    where cleared_at is null;
create index ix_nba_sod_violation_found on nba_sod_violation (found_at desc);

-- ---------- 2. Certification extracts --------------------------------------------------------------
create table nba_certification_extract (
    id          bigint generated by default as identity primary key,
    file_name   varchar(100) not null,
    file_format varchar(10)  not null,
    row_count   integer      not null,
    sha256      varchar(64)  not null,
    taken_by    varchar(50)  not null,
    taken_at    timestamptz  not null,
    constraint ck_nba_cert_extract_format check (file_format in ('CSV', 'XLSX')),
    constraint ck_nba_cert_extract_rows check (row_count >= 0),
    constraint ck_nba_cert_extract_sha256 check (sha256 ~ '^[0-9a-f]{64}$')
);
create index ix_nba_cert_extract_taken on nba_certification_extract (taken_at desc);

-- ---------- 3. Notices ---------------------------------------------------------------------------------
insert into msg_notification_event (code, name, module, description, default_in_app, default_email, sort_order) values
    ('UAM_SOD_VIOLATION', 'Separation-of-duties breach found', 'USER_ACCESS',
     'The daily check found users whose group profiles breach an active separation-of-duties rule', true, true, 700),
    ('UAM_CERTIFICATION_EXTRACT', 'Certification extract taken', 'USER_ACCESS',
     'A certification extract of the accounts, group profiles and permissions was taken', true, true, 710)
on conflict (code) do nothing;

update msg_notification_event set name = 'Group profile change to approve',
    description = 'A group-profile change waits for your approval'
where code = 'UAM_REQUEST_TO_APPROVE';
update msg_notification_event set name = 'Group profile change returned',
    description = 'Your group-profile change was returned for correction'
where code = 'UAM_REQUEST_RETURNED';
update msg_notification_event set name = 'Group profile change cancelled',
    description = 'A group-profile change was cancelled'
where code = 'UAM_REQUEST_CANCELLED';
update msg_notification_event set name = 'Group profile change decided',
    description = 'Your group-profile change was approved or rejected'
where code = 'UAM_REQUEST_DECIDED';
update msg_notification_event set name = 'Group profile change for second approval',
    description = 'A privileged group-profile change waits for the second approval'
where code = 'UAM_SECOND_APPROVAL';
update msg_notification_event set name = 'Group profile change to implement',
    description = 'An approved group-profile change waits to be implemented'
where code = 'UAM_FOR_IMPLEMENTATION';
update msg_notification_event set name = 'Password expiry (local test accounts)',
    description = 'The password of a local test account expires soon; the bank''s users sign in at Microsoft Entra ID'
where code = 'PASSWORD_EXPIRY_NOTICE';
