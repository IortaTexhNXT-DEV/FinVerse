-- Full insurer page (Sprint 2, G08): payment terms and remittance details on the insurer profile,
-- the insurer's contact persons and its bank accounts. All of them follow maker-checker: a change
-- is pending until another user authorizes it, and the change log (G05) keeps every field change.
alter table cat_insurer
    add column payment_terms     varchar(300),
    add column remittance_cycle  varchar(12),
    add column remittance_mode   varchar(20),
    add column remittance_email  varchar(120),
    add column remittance_currency varchar(3),
    add constraint ck_cat_insurer_remittance_cycle
        check (remittance_cycle is null or remittance_cycle in ('DAILY', 'WEEKLY', 'SEMI_MONTHLY', 'MONTHLY')),
    add constraint ck_cat_insurer_remittance_mode
        check (remittance_mode is null or remittance_mode in ('CHECK', 'FUND_TRANSFER', 'ONLINE_BANKING'));

create table cat_insurer_contact (
    id              bigint generated by default as identity primary key,
    version         bigint        not null default 0,
    insurer_id      bigint        not null references cat_insurer (id),
    contact_role    varchar(20)   not null,
    name            varchar(150)  not null,
    position        varchar(80),
    email           varchar(120),
    phone           varchar(40),
    record_status   varchar(30)   not null,
    authorized_by   varchar(50),
    authorized_at   timestamptz,
    created_at      timestamptz   not null,
    created_by      varchar(50)   not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint ck_cat_insurer_contact_role
        check (contact_role in ('PLACEMENT', 'CLAIMS', 'ACCOUNTING', 'REMITTANCE', 'RELATIONSHIP', 'OTHER'))
);
create index ix_cat_insurer_contact_insurer on cat_insurer_contact (insurer_id);

create table cat_insurer_bank_account (
    id              bigint generated by default as identity primary key,
    version         bigint        not null default 0,
    insurer_id      bigint        not null references cat_insurer (id),
    purpose         varchar(20)   not null,
    bank_name       varchar(120)  not null,
    bank_branch     varchar(120),
    account_no      varchar(40)   not null,
    account_name    varchar(250)  not null,
    currency        varchar(3)    not null,
    primary_account boolean       not null default false,
    record_status   varchar(30)   not null,
    authorized_by   varchar(50),
    authorized_at   timestamptz,
    created_at      timestamptz   not null,
    created_by      varchar(50)   not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint uq_cat_insurer_bank_account unique (insurer_id, account_no),
    constraint ck_cat_insurer_bank_account_purpose
        check (purpose in ('REMITTANCE', 'REFUND', 'COMMISSION'))
);
create index ix_cat_insurer_bank_account_insurer on cat_insurer_bank_account (insurer_id);
