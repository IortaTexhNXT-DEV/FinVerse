-- Daily service-invoice batch per insurer (Sprint 2, G09): once a day the SI_DAILY_BATCH job groups
-- the service invoices issued to each insurer on the business date into one batch, sent to the
-- insurer's billing address in one e-mail. One batch per company, insurer and date (idempotent);
-- the delivery status follows the e-mail (generated, sent, failed, retried) and a failed batch can be
-- sent again from the batch screen.
create table bkg_si_batch (
    id               bigint generated by default as identity primary key,
    version          bigint         not null default 0,
    company_id       bigint         not null references org_company (id),
    insurer_code     varchar(30)    not null,
    insurer_name     varchar(250)   not null,
    batch_date       date           not null,
    item_count       integer        not null,
    currency         varchar(3),
    commission_total numeric(19, 2) not null,
    net_total        numeric(19, 2) not null,
    delivery_status  varchar(12)    not null,
    attempts         integer        not null default 0,
    recipient_email  varchar(300),
    message_id       bigint,
    last_error       varchar(1000),
    sent_at          timestamptz,
    created_at       timestamptz    not null,
    created_by       varchar(50)    not null,
    updated_at       timestamptz,
    updated_by       varchar(50),
    constraint uq_bkg_si_batch unique (company_id, insurer_code, batch_date),
    constraint ck_bkg_si_batch_status check (delivery_status in ('GENERATED', 'SENT', 'FAILED', 'RETRIED'))
);
create index ix_bkg_si_batch_date on bkg_si_batch (company_id, batch_date);

create table bkg_si_batch_item (
    batch_id           bigint not null references bkg_si_batch (id) on delete cascade,
    service_invoice_id bigint not null references bkg_service_invoice (id),
    constraint pk_bkg_si_batch_item primary key (batch_id, service_invoice_id),
    constraint uq_bkg_si_batch_item_si unique (service_invoice_id)
);
