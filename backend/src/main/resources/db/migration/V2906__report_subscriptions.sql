-- Report scheduling and subscriptions (Sprint 2, G04): a user subscribes to a report with its
-- parameters, a frequency (daily, weekly or monthly), a file format and the e-mail recipients. The
-- REPORT_SUBSCRIPTIONS job runs the subscriptions due on the business date as the subscriber, with
-- the subscriber's report permissions and data scope checked at run time, archives the file in the
-- report archive, e-mails it and records each run (one per subscription and date).
create table report_subscription (
    id             bigint generated by default as identity primary key,
    version        bigint        not null default 0,
    report_code    varchar(40)   not null,
    username       varchar(50)   not null,
    parameters     varchar(2000) not null,
    frequency      varchar(10)   not null,
    day_of_week    integer,
    day_of_month   integer,
    format         varchar(10)   not null,
    recipients     varchar(1000) not null,
    active         boolean       not null default true,
    last_run_date  date,
    created_at     timestamptz   not null,
    created_by     varchar(50)   not null,
    updated_at     timestamptz,
    updated_by     varchar(50),
    constraint ck_report_subscription_frequency check (frequency in ('DAILY', 'WEEKLY', 'MONTHLY')),
    constraint ck_report_subscription_dow check (day_of_week is null or day_of_week between 1 and 7),
    constraint ck_report_subscription_dom check (day_of_month is null or day_of_month between 1 and 31)
);
create index ix_report_subscription_user on report_subscription (username);

create table report_subscription_run (
    id              bigint generated by default as identity primary key,
    version         bigint        not null default 0,
    subscription_id bigint        not null references report_subscription (id),
    run_date        date          not null,
    status          varchar(12)   not null,
    report_run_id   bigint references report_run (id),
    row_count       integer       not null default 0,
    message_id      bigint,
    detail          varchar(1000),
    created_at      timestamptz   not null,
    created_by      varchar(50)   not null,
    updated_at      timestamptz,
    updated_by      varchar(50),
    constraint uq_report_subscription_run unique (subscription_id, run_date),
    constraint ck_report_subscription_run_status check (status in ('SUCCEEDED', 'FAILED', 'DENIED'))
);
create index ix_report_subscription_run_report on report_subscription_run (report_run_id);
