-- =====================================================================================
-- iNXT BrokerVerse - V2907 Customer Servicing Facility (BRD-9) case management: the cases of the
-- contact centre with their notes, the turnaround times of the case types, the routing table, the
-- members of the fulfilment units, the role of the fulfilment units, the case permissions, the
-- case lists of values and the case parameters.
--   Requirements: CSF addendum Case Management BRCSFCM.001-012; FRS BRD-9 FR-CSF-050 to 061,
--   sections 3, 5.3 and 9. The case history is the platform audit trail (entity CsfCase).
--   The lists below are the values named in the FRS; the full lists of the addendum (natures of
--   transaction, product types, market segments and fulfilment units) are loaded by the System
--   Administrator on the Lists of Values screen from the list Contact Center Management provides
--   (CSQ19). Values are deactivated, never deleted, so old cases keep them.
-- =====================================================================================

-- ---------- Cases ----------------------------------------------------------------------------------
create table csf_case (
    id                bigint generated by default as identity primary key,
    version           bigint        not null default 0,
    company_id        bigint        not null references org_company (id),
    case_no           varchar(30)   not null,
    client_id         bigint        references crm_client (id),
    client_code       varchar(40),
    client_name       varchar(300),
    caller_name       varchar(200),
    caller_contact    varchar(200),
    account_id        bigint        references acc_account (id),
    arn               varchar(40),
    policy_no         varchar(100),
    channel           varchar(40)   not null,
    case_type         varchar(40)   not null,
    nature            varchar(40)   not null,
    product_type      varchar(40)   not null,
    market_segment    varchar(40)   not null,
    fulfilment_unit   varchar(40)   not null,
    priority          varchar(40)   not null,
    subject           varchar(150)  not null,
    description       varchar(4000) not null,
    status            varchar(30)   not null,
    owner             varchar(50)   not null,
    agent             varchar(50)   not null,
    tat_days          integer       not null,
    due_date          date          not null,
    sla_status        varchar(20)   not null default 'WITHIN_TAT',
    near_notified     boolean       not null default false,
    breach_notified   boolean       not null default false,
    escalated         boolean       not null default false,
    escalation_reason varchar(40),
    escalated_at      timestamptz,
    return_reason     varchar(40),
    instruction       varchar(4000),
    resolution        varchar(4000),
    closure_reason    varchar(40),
    closed_at         timestamptz,
    closed_by         varchar(50),
    parent_case_id    bigint        references csf_case (id),
    follow_up_reason  varchar(500),
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    updated_at        timestamptz,
    updated_by        varchar(50),
    constraint uq_csf_case_no unique (case_no),
    constraint ck_csf_case_status check (status in ('WITH_FULFILMENT', 'RETURNED_TO_AGENT',
        'CSR_ACTION_REQUIRED', 'CLOSED_BY_FULFILMENT', 'CLOSED_BY_CSR')),
    constraint ck_csf_case_sla check (sla_status in ('WITHIN_TAT', 'APPROACHING', 'BREACHED')),
    constraint ck_csf_case_party check (client_id is not null or caller_name is not null)
);
create index ix_csf_case_company on csf_case (company_id, status, created_at);
create index ix_csf_case_client on csf_case (client_id);
create index ix_csf_case_account on csf_case (account_id);
create index ix_csf_case_parent on csf_case (parent_case_id);
create index ix_csf_case_owner on csf_case (lower(owner), status);
create index ix_csf_case_unit on csf_case (fulfilment_unit, status);

create table csf_case_note (
    id         bigint generated by default as identity primary key,
    case_id    bigint        not null references csf_case (id),
    note       varchar(4000) not null,
    author     varchar(50)   not null,
    created_at timestamptz   not null
);
create index ix_csf_case_note_case on csf_case_note (case_id, created_at);

-- ---------- Turnaround times, routing and fulfilment unit members (configuration) ----------------
create table csf_case_type_setting (
    id             bigint generated by default as identity primary key,
    version        bigint      not null default 0,
    case_type      varchar(40) not null,
    tat_days       integer     not null,
    auto_escalate  boolean     not null default true,
    created_at     timestamptz not null,
    created_by     varchar(50) not null,
    updated_at     timestamptz,
    updated_by     varchar(50),
    constraint uq_csf_case_type_setting unique (case_type),
    constraint ck_csf_case_type_tat check (tat_days between 0 and 365)
);

-- One row per case type, market segment and nature of transaction; a blank (empty text) matches
-- any value. The most specific active row applies.
create table csf_case_routing (
    id               bigint generated by default as identity primary key,
    version          bigint      not null default 0,
    case_type        varchar(40) not null default '',
    market_segment   varchar(40) not null default '',
    nature           varchar(40) not null default '',
    fulfilment_unit  varchar(40) not null,
    escalation_group varchar(40),
    active           boolean     not null default true,
    created_at       timestamptz not null,
    created_by       varchar(50) not null,
    updated_at       timestamptz,
    updated_by       varchar(50),
    constraint uq_csf_case_routing unique (case_type, market_segment, nature)
);

create table csf_fulfilment_member (
    id         bigint generated by default as identity primary key,
    unit_code  varchar(40) not null,
    username   varchar(50) not null,
    created_at timestamptz not null,
    created_by varchar(50) not null,
    constraint uq_csf_fulfilment_member unique (unit_code, username)
);
create index ix_csf_fulfilment_member_user on csf_fulfilment_member (lower(username));

-- ---------- Role and grants (FRS BRD-9 section 3.3) ------------------------------------------------
insert into sec_role (code, name, created_at, created_by)
values ('CSF_FULFILMENT', 'Customer Service Fulfilment Unit', now(), 'SYSTEM')
on conflict (code) do nothing;

insert into sec_role_permission (role_id, permission)
select r.id, g.permission
from sec_role r
join (values
    ('CSF_AGENT', 'CSF_CASE_CREATE'),
    ('CSF_SUPERVISOR', 'CSF_CASE_CREATE'), ('CSF_SUPERVISOR', 'CSF_CASE_SUPERVISE'),
    ('CSF_SUPERVISOR', 'CSF_CASE_REPORT'),
    ('CSF_MANAGEMENT', 'CSF_CASE_REPORT'),
    ('CSF_FULFILMENT', 'CSF_CASE_FULFIL'), ('CSF_FULFILMENT', 'ATTACHMENT_VIEW'),
    ('SYSADMIN', 'CSF_CASE_ROUTING')
) as g(role_code, permission) on g.role_code = r.code
where not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = g.permission);

insert into sec_permission_action (permission, area, action)
values ('CSF_CASE_CREATE', 'CUSTOMER_SERVICE', 'CREATE'),
       ('CSF_CASE_SUPERVISE', 'CUSTOMER_SERVICE', 'APPROVE'),
       ('CSF_CASE_FULFIL', 'CUSTOMER_SERVICE', 'AMEND'),
       ('CSF_CASE_REPORT', 'CUSTOMER_SERVICE', 'VIEW'),
       ('CSF_CASE_ROUTING', 'CUSTOMER_SERVICE', 'AMEND')
on conflict (permission, action) do nothing;

