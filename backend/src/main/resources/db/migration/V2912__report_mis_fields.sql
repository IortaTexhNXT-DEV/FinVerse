-- MIS fields catalogue of the reports (Sprint 4, gap G06, FR-CR-062): the business label of each data
-- element of a core entity (user, product, insurer, claim, account, transaction), offered with the same
-- label for grouping in the Layout panel of the report runner (FR-CR-042). Maintained by the System
-- Administrator under maker-checker (MIS_FIELD_MAINTAIN, MIS_FIELD_AUTHORIZE); every change is in the
-- Master Data Change Log. Delivered with the fields of BR-173 and the MIS columns of the Report List.
create table rpt_mis_field (
    id            bigint generated by default as identity primary key,
    version       bigint       not null default 0,
    code          varchar(40)  not null,
    label         varchar(80)  not null,
    entity        varchar(20)  not null,
    source        varchar(40)  not null,
    lov_type      varchar(60),
    record_status varchar(30)  not null default 'PENDING_AUTHORIZATION',
    authorized_by varchar(50),
    authorized_at timestamptz,
    created_at    timestamptz  not null,
    created_by    varchar(50)  not null,
    updated_at    timestamptz,
    updated_by    varchar(50),
    constraint uq_rpt_mis_field_code unique (code),
    constraint ck_rpt_mis_field_status check (record_status in ('PENDING_AUTHORIZATION', 'ACTIVE', 'INACTIVE')),
    constraint ck_rpt_mis_field_entity check (entity in ('USER', 'PRODUCT', 'INSURER', 'CLAIM', 'ACCOUNT', 'TRANSACTION'))
);
create unique index uq_rpt_mis_field_source on rpt_mis_field (source) where record_status <> 'INACTIVE';

