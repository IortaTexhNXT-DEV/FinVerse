-- Default co-insurance participation of an insurer (BRD-00 CRQ08, Risk Participation; client decision of
-- 17-Oct-2026: co-insurance is in scope, only reinsurance is deferred to Phase 2). The participating insurers of an
-- insurer's default arrangement with their share, the lead flag and the effective dates. Maker-checker like the
-- other parts of the insurer page: a row is pending until another user authorizes it, and the change log (G05)
-- keeps every field change. Booking uses the authorized shares effective on the booking date as the default
-- co-insurance split of an invoice (FR-OP-007) when none is entered and they total 100 %.
create table cat_insurer_participation (
    id                bigint generated by default as identity primary key,
    version           bigint        not null default 0,
    insurer_id        bigint        not null references cat_insurer (id),
    participant_code  varchar(30)   not null,
    share_pct         numeric(9, 4) not null check (share_pct > 0 and share_pct <= 100),
    lead              boolean       not null,
    effective_from    date          not null,
    effective_to      date,
    record_status     varchar(30)   not null,
    authorized_by     varchar(50),
    authorized_at     timestamptz,
    created_at        timestamptz   not null,
    created_by        varchar(50)   not null,
    updated_at        timestamptz,
    updated_by        varchar(50),
    constraint ck_cat_insurer_participation_dates check (effective_to is null or effective_to >= effective_from)
);
create index ix_cat_insurer_participation_insurer on cat_insurer_participation (insurer_id);
