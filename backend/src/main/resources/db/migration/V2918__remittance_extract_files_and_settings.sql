-- Remittance extract files and settings (FRS BRD-02 Operations Remittance v1.0, FRID.RMT.001, 003, 008, 014; ICD
-- IF-RMT-01 to IF-RMT-04).
--
-- 1. Settlement number of a batch: a running number per insurer, shown with 8 digits; the insurer code and the
--    settlement number name the extract files and appear on the insurer's OR.
alter table rem_batch add column settlement_no varchar(8);
alter table rem_batch add column settlement_ref varchar(40);
create unique index uq_rem_batch_settlement_ref on rem_batch (company_id, settlement_ref);

-- 2. Mall Assurance deductions of an account (columns 25 to 31 of the Excel extract); zero until the source of the
--    Mall Assurance charges is confirmed (Q-RM-05).
alter table rem_batch_line add column mall_payment_mode varchar(30);
alter table rem_batch_line add column mall_service_charge numeric(19, 2) not null default 0;
alter table rem_batch_line add column mall_card_charge numeric(19, 2) not null default 0;
alter table rem_batch_line add column mall_vat numeric(19, 2) not null default 0;
alter table rem_batch_line add column mall_wtax numeric(19, 2) not null default 0;

-- 3. Remittance Settings (FRID.RMT.003): extraction schedule, shared folders and file naming, kept as changes
--    proposed by a maker and approved by the Remittance Team Leader. The settings in force are the latest
--    approved change of the company.
create table rem_setting_change (
    id                      bigint generated by default as identity primary key,
    version                 bigint         not null default 0,
    company_id              bigint         not null references org_company (id),
    schedule_active         boolean        not null,
    extraction_time         varchar(5)     not null,
    working_days_only       boolean        not null,
    folder_normal_php       varchar(250)   not null,
    folder_normal_usd       varchar(250)   not null,
    folder_with_incentives  varchar(250)   not null,
    file_pattern            varchar(120)   not null,
    text_prefix             varchar(10)    not null,
    reason                  varchar(250)   not null,
    status                  varchar(20)    not null check (status in ('PENDING', 'APPROVED', 'REJECTED', 'SUPERSEDED')),
    requested_by            varchar(50)    not null,
    requested_at            timestamptz    not null,
    decided_by              varchar(50),
    decided_at              timestamptz,
    decision_comment        varchar(250)
);
create index ix_rem_setting_change_company on rem_setting_change (company_id, status);

-- 4. Copies of the extract files to the shared folder (IF-RMT-04), one row per file and attempt.
create table rem_file_delivery (
    id                      bigint generated by default as identity primary key,
    batch_id                bigint         not null references rem_batch (id),
    stage                   varchar(20)    not null check (stage in ('CREATED', 'APPROVED', 'RESENT')),
    file_name               varchar(120)   not null,
    folder                  varchar(250)   not null,
    status                  varchar(20)    not null check (status in ('DELIVERED', 'FAILED')),
    reference               varchar(120),
    error                   varchar(250),
    attempted_at            timestamptz    not null,
    attempted_by            varchar(50)
);
create index ix_rem_file_delivery_batch on rem_file_delivery (batch_id);

-- 5. Permissions: the maker of a settings change and its approver (the Remittance Team Leader).
insert into sec_permission_action (permission, area, action)
values ('REMIT_SETTINGS_MAINTAIN', 'REMITTANCE', 'AMEND'),
       ('REMIT_SETTINGS_APPROVE', 'REMITTANCE', 'APPROVE')
on conflict (permission, action) do nothing;

insert into sec_role_permission (role_id, permission)
select r.id, g.permission
from sec_role r
join (values ('REMIT_PROCESSOR', 'REMIT_SETTINGS_MAINTAIN'), ('REMIT_TL', 'REMIT_SETTINGS_MAINTAIN'),
             ('REMIT_TL', 'REMIT_SETTINGS_APPROVE')) as g(role_code, permission)
  on g.role_code = r.code
where not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = g.permission);

-- 6. Alert when a copy of the extract files to the shared folder fails (IF-RMT-04); the files stay downloadable
--    from the batch and the copy can be sent again.
insert into alt_exception_code (code, name, description, module, severity, threshold_amount, threshold_days,
                                created_at, created_by)
values ('REMIT_SHARED_FOLDER_FAILED', 'Remittance files not copied to the shared folder',
        'The extract files of a remittance batch could not be copied to the shared folder of its remittance type.',
        'REMITTANCE', 'HIGH', null, null, now(), 'SYSTEM')
on conflict (code) do nothing;
