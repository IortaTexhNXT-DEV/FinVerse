-- --------------------------------------------------------------- permissions --
-- Checker permission for treaties, facultative placements and statements of account.
insert into sec_role_permission (role_id, permission)
select r.id, 'REINSURANCE_AUTHORIZE' from sec_role r
where r.code in ('FIN_MANAGER', 'AUTHORIZER')
  and not exists (select 1 from sec_role_permission x
                  where x.role_id = r.id and x.permission = 'REINSURANCE_AUTHORIZE');
