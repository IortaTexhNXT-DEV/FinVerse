 ('CLAIM_MARGIN_PROVISION', 'ULAE and risk margin provision', 'PROVISION', 'PROVISION',
  'Change in the ULAE provision and the margin for adverse deviation (gross and reinsurers share)',
  'ULAE_CHANGE,MFAD_CHANGE,RI_MFAD_CHANGE'),
 ('PREMIUM_DEFICIENCY_PROVISION', 'Premium deficiency reserve', 'PROVISION', 'PROVISION',
  'Change in the premium deficiency reserve from the liability adequacy test', 'PDR_CHANGE');

