create index ix_pcd_fund on pay_petty_cash_disbursement (fund_id, status, disbursement_date);
create index ix_pcd_reimbursement on pay_petty_cash_disbursement (reimbursement_id);

-- ---------- Accounting events -------------------------------------------------------------------
-- A post-dated cheque is accounted for in two steps (see IssuedPdcService):
--   issue    : the party's payment event (SUPPLIER_PAYMENT, CLAIM_PAYMENT...) with role BANK set to
--              the bank account's PDC-issued clearing account (Dr payable / Cr PDC clearing);
--   maturity : PDC_ISSUED_PRESENTED on the presentation date (Dr PDC clearing / Cr bank).
insert into acc_event_type (code, name, category, journal_type, description, amount_components) values
 ('PDC_ISSUED_PRESENTED', 'Issued PDC presented', 'PAYMENT', 'PAYMENT',
  'Post-dated cheque issued has matured and was presented: clears the PDC liability against the bank (roles PDC_CLEARING, BANK)',
  'AMOUNT');
