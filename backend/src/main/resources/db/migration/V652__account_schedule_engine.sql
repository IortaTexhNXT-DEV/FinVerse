insert into fin_schedule_def (code, name, family, source_ref, description, selector_kind,
    account_selector, grouping_key, currency, balance_side, basis, ageing, ageing_slots, comparative,
    commentary, board_document, layout_status, active, created_at, created_by)
select s.code, s.name, s.family, s.source_ref,
       'Draft definition seeded from the BDOI report pack; layout to confirm with FRBS (AQ05).',
       'ACCOUNT_PREFIX', s.selector, s.grouping_key, s.currency, s.side, s.basis, s.slots is not null,
       s.slots, s.comparative, s.commentary, s.board, 'TO_CONFIRM', true, now(), 'SYSTEM'
from fin_schedule_seed s
order by s.seq;

insert into fin_schedule_column (schedule_id, seq, measure, label)
select d.id, m.ord * 10, m.measure,
       case m.measure
           when 'OPENING' then 'Opening balance'
           when 'DEBITS' then 'Debits'
           when 'CREDITS' then 'Credits'
           when 'MOVEMENT' then case when s.basis = 'MOVEMENT' then 'This period' else 'Movement' end
           when 'CLOSING' then case when s.basis = 'MOVEMENT' then 'Year to date' else 'Balance' end
           when 'COMPARATIVE' then case s.comparative when 'PREVIOUS_YEAR' then 'Previous year'
                                                      else 'Previous month' end
           when 'VARIANCE' then 'Variance'
           else 'Variance %'
       end
from fin_schedule_seed s
join fin_schedule_def d on d.code = s.code
cross join lateral unnest(string_to_array(s.measures, ',')) with ordinality as m(measure, ord);
