-- =====================================================================================
-- iNXT BrokerVerse - V652 Account schedule engine (finreport, BRD-5 wave A1-FRBS)
--   FRBS 3.2.0, Appendix A II-IV (GARD bank-format schedules, subsidiaries accounting, schedules
--   and aging); BDOI report list #9, #45, #46 (docs/requirements/BDOI_REPORT_LIST.md);
--   docs/architecture/ACCOUNTING_DISBURSEMENT_DESIGN.md sections 10 and 12.1.
--
--   * fin_schedule_def       one definition per schedule: the accounts (code prefixes or report
--                            groups), the grouping (account, party, document, cost centre, branch,
--                            business line), the currency, the natural side, the basis (balance or
--                            period movement), optional ageing (up to 8 buckets), a comparative
--                            period (previous month / previous year) and a commentary column
--   * fin_schedule_column    the measures shown, in order
--   * fin_statement_comment  commentary per company, schedule, month and row (variance analysis
--                            with commentary, Appendix A II-45)
--
-- The definitions below are drafts: BDOI has given titles only, so every layout is TO_CONFIRM
-- (AQ05) and the account selectors point at the demo chart until FRBS uploads the real chart
-- (FRBS 2.3.1, AQ01). They are configuration, maintained on the Account Schedules screen; no code
-- refers to an account code. No foreign key to broking tables (design section 4).
-- =====================================================================================

create table fin_schedule_def (
    id               bigint generated by default as identity primary key,
    version          bigint        not null default 0,
    code             varchar(40)   not null,
    name             varchar(200)  not null,
    family           varchar(20)   not null
        constraint fin_ck_schedule_family check (family in ('GARD', 'SUBSIDIARIES', 'SCHEDULE',
            'AGING', 'OTHER')),
    source_ref       varchar(80),
    description      varchar(500),
    selector_kind    varchar(20)   not null
        constraint fin_ck_schedule_selector check (selector_kind in ('ACCOUNT_PREFIX', 'REPORT_GROUP')),
    account_selector varchar(500)  not null,
    grouping_key     varchar(20)   not null
        constraint fin_ck_schedule_grouping check (grouping_key in ('ACCOUNT', 'PARTY', 'DOCUMENT',
            'COST_CENTER', 'BRANCH', 'BUSINESS_LINE')),
    currency         varchar(3),
    balance_side     varchar(6)    not null
        constraint fin_ck_schedule_side check (balance_side in ('DEBIT', 'CREDIT')),
    basis            varchar(10)   not null
        constraint fin_ck_schedule_basis check (basis in ('BALANCE', 'MOVEMENT')),
    ageing           boolean       not null default false,
    ageing_slots     varchar(60),
    comparative      varchar(20)   not null default 'NONE'
        constraint fin_ck_schedule_comparative check (comparative in ('NONE', 'PREVIOUS_MONTH',
            'PREVIOUS_YEAR')),
    commentary       boolean       not null default false,
    board_document   boolean       not null default false,
    layout_status    varchar(20)   not null default 'TO_CONFIRM'
        constraint fin_ck_schedule_layout check (layout_status in ('TO_CONFIRM', 'CONFIRMED')),
    active           boolean       not null default true,
    created_at       timestamptz   not null,
    created_by       varchar(50)   not null,
    updated_at       timestamptz,
    updated_by       varchar(50),
    constraint fin_uq_schedule_code unique (code),
    constraint fin_ck_schedule_ageing check (not ageing or ageing_slots is not null),
    constraint fin_ck_schedule_ageing_basis check (not ageing or basis = 'BALANCE')
);

create table fin_schedule_column (
    id          bigint generated by default as identity primary key,
    schedule_id bigint       not null references fin_schedule_def (id) on delete cascade,
    seq         integer      not null,
    measure     varchar(20)  not null
        constraint fin_ck_schedule_measure check (measure in ('OPENING', 'DEBITS', 'CREDITS',
            'MOVEMENT', 'CLOSING', 'COMPARATIVE', 'VARIANCE', 'VARIANCE_PCT')),
    label       varchar(60)  not null,
    constraint fin_uq_schedule_column unique (schedule_id, measure)
);
create index ix_fin_schedule_column on fin_schedule_column (schedule_id, seq);

create table fin_statement_comment (
    id            bigint generated by default as identity primary key,
    version       bigint        not null default 0,
    company_id    bigint        not null references org_company (id),
    schedule_code varchar(40)   not null,
    period        varchar(7)    not null
        constraint fin_ck_comment_period check (period ~ '^[0-9]{4}-[0-9]{2}$'),
    row_key       varchar(120)  not null,
    comment_text  varchar(1000) not null,
    created_at    timestamptz   not null,
    created_by    varchar(50)   not null,
    updated_at    timestamptz,
    updated_by    varchar(50),
    constraint fin_uq_statement_comment unique (company_id, schedule_code, period, row_key)
);

