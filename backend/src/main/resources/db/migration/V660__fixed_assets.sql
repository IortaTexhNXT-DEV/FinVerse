  'Existing asset taken on with its accumulated depreciation (roles ASSET, ACCUM_DEPRECIATION)',
  'COST,ACCUMULATED_DEPRECIATION,NET_BOOK_VALUE'),
 ('ASSET_DEPRECIATION', 'Monthly depreciation', 'PROVISION', 'PROVISION',
  'Depreciation charge of a period (roles DEPRECIATION_EXPENSE, ACCUM_DEPRECIATION)', 'DEPRECIATION'),
 ('ASSET_DISPOSAL', 'Fixed asset disposal', 'RECEIPT', 'RECEIPT',
  'Derecognition with sale proceeds and gain or loss (roles ASSET, ACCUM_DEPRECIATION, BANK)',
  'COST,ACCUMULATED_DEPRECIATION,PROCEEDS,GAIN,LOSS'),
 ('ASSET_TRANSFER', 'Inter-branch asset transfer', 'PROVISION', 'PROVISION',
  'Receiving branch positive, sending branch negative amounts (roles ASSET, ACCUM_DEPRECIATION)',
  'COST,ACCUMULATED_DEPRECIATION,NET_BOOK_VALUE');
