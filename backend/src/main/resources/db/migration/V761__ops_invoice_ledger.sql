-- ---------- Default Disbursement queue (DisbursementGateway default adapter, OQ02) ----------
create table ops_disbursement_request (
    id           bigint generated by default as identity primary key,
    version      bigint         not null default 0,
    company_id   bigint         not null references org_company (id),
    request_no   varchar(30)    not null unique,
    request_type varchar(20)    not null check (request_type in ('REMITTANCE', 'REFUND', 'CWT2307', 'PASS_ON')),
    source_module varchar(30)   not null,
    source_ref   varchar(80)    not null,
    payee_code   varchar(30)    not null,
    payee_name   varchar(250),
    currency     varchar(3)     not null,
    amount       numeric(19, 2) not null check (amount > 0),
    description  varchar(500),
    status       varchar(20)    not null check (status in ('SENT', 'ACKNOWLEDGED', 'DV_ASSIGNED', 'PAID', 'RETURNED')),
    dv_no        varchar(40),
    sent_at      timestamptz    not null,
    acknowledged_at timestamptz,
    dv_assigned_at  timestamptz,
    paid_at      timestamptz,
    returned_at  timestamptz,
    return_reason varchar(250),
    attachment_ref varchar(80),
    created_at   timestamptz    not null,
    created_by   varchar(50)    not null,
    updated_at   timestamptz,
    updated_by   varchar(50),
    constraint uq_ops_disbursement_source unique (source_module, source_ref)
);
create index ix_ops_disbursement_status on ops_disbursement_request (company_id, status);

-- ---------- In-system extract repository (FileDropPort default adapter, OQ17) --------------
create table ops_extract_file (
    id           bigint generated by default as identity primary key,
    version      bigint        not null default 0,
    company_id   bigint        not null references org_company (id),
    folder       varchar(120)  not null,
    file_name    varchar(255)  not null,
    content_type varchar(100)  not null,
    size_bytes   bigint        not null,
    sha256       varchar(64)   not null,
    content      bytea         not null,
    source_module varchar(30)  not null,
    source_ref   varchar(80),
    created_at   timestamptz   not null,
    created_by   varchar(50)   not null,
    updated_at   timestamptz,
    updated_by   varchar(50),
    constraint uq_ops_extract_file unique (company_id, folder, file_name)
);

-- ---------- Hand-offs of the default port adapters ------------------------------------------
create table ops_handoff (
    id           bigint generated by default as identity primary key,
    version      bigint         not null default 0,
    company_id   bigint         not null references org_company (id),
    port         varchar(40)    not null,
    source_module varchar(30)   not null,
    source_ref   varchar(80)    not null,
    reference    varchar(80),
    amount       numeric(19, 2),
    currency     varchar(3),
    summary      varchar(500)   not null,
    payload      text,
    status       varchar(20)    not null check (status in ('OPEN', 'CLOSED')),
    closed_at    timestamptz,
    closed_by    varchar(50),
    closing_note varchar(250),
    created_at   timestamptz    not null,
    created_by   varchar(50)    not null,
    updated_at   timestamptz,
    updated_by   varchar(50),
    constraint uq_ops_handoff unique (port, source_module, source_ref)
);
create index ix_ops_handoff_open on ops_handoff (company_id, status);
