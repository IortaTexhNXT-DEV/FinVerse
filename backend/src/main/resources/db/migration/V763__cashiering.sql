-- ---------- Receipt series (CSHID.006/015, OQ05) ----------------------------------------------
create table csh_receipt_series (
    id             bigint generated by default as identity primary key,
    version        bigint       not null default 0,
    company_id     bigint       not null references org_company (id),
    branch_id      bigint       not null references org_branch (id),
    kind           varchar(2)   not null check (kind in ('AR', 'OR')),
    atp_no         varchar(40),
    prefix         varchar(20)  not null,
    from_no        bigint       not null check (from_no > 0),
    to_no          bigint       not null,
    next_no        bigint       not null,
    warn_at        integer      not null default 0 check (warn_at >= 0),
    record_status  varchar(30)  not null,
    authorized_by  varchar(50),
    authorized_at  timestamptz,
    created_at     timestamptz  not null,
    created_by     varchar(50)  not null,
    updated_at     timestamptz,
    updated_by     varchar(50),
    constraint ck_csh_series_range check (to_no >= from_no and next_no between from_no and to_no + 1),
    constraint uq_csh_series_prefix unique (company_id, prefix, from_no)
);
create index ix_csh_series_branch on csh_receipt_series (company_id, branch_id, kind);

-- ---------- Receipts: AR and OR (CSHID.001/002) ----------------------------------------------
create table csh_receipt (
    id                bigint generated by default as identity primary key,
