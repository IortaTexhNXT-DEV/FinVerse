    payor_name        varchar(250)   not null,
    assured_name      varchar(250),
    sales_unit        varchar(40),
    currency          varchar(3)     not null,
    book_rate         numeric(19, 2) not null,
    amount            numeric(19, 2) not null check (amount >= 0),
    base_amount       numeric(19, 2) not null,
    gross             numeric(19, 2) not null default 0,
    vat               numeric(19, 2) not null default 0,
    wtax              numeric(19, 2) not null default 0,
    applied_amount    numeric(19, 2) not null default 0,
    payment_mode      varchar(20)    not null,
    check_no          varchar(40),
    check_bank        varchar(60),
    check_date        date,
    certificate_ref   varchar(60),
    source            varchar(20)    not null,
    source_module     varchar(30),
    source_ref        varchar(80),
    status            varchar(20)    not null check (status in ('ISSUED', 'CANCELLED', 'REINSTATED')),
