create table rem_incentive_rule (
    id               bigint generated by default as identity primary key,
    version          bigint         not null default 0,
    company_id       bigint         not null references org_company (id),
    insurer_code     varchar(30)    not null,
    product_line     varchar(30),
    segment          varchar(40),
    rate             numeric(9, 4)  not null check (rate > 0 and rate <= 100),
    window_days      integer        not null check (window_days between 1 and 366),
    basis            varchar(20)    not null check (basis in ('INCEPTION', 'BOOKING')),
    effective_from   date           not null,
    effective_to     date,
    active           boolean        not null default true,
    description      varchar(250),
    created_at       timestamptz    not null,
    created_by       varchar(50)    not null,
    updated_at       timestamptz,
    updated_by       varchar(50),
    constraint ck_rem_incentive_rule_period check (effective_to is null or effective_to >= effective_from)
);
create index ix_rem_incentive_rule on rem_incentive_rule (company_id, insurer_code, active);

