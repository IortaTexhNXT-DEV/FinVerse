    run_id                  bigint         references rem_extraction_run (id),
    special_request_no      varchar(30),
    processor               varchar(50),
    stage                   varchar(30)    not null check (stage in ('REVIEW_IN_PROCESS', 'FOR_APPROVAL', 'ON_HOLD',
                                                                     'APPROVED', 'PARTIALLY_REMITTED',
                                                                     'FULLY_REMITTED', 'OR_RECEIVED', 'RETURNED')),
    line_count              integer        not null default 0,
    paid_ar                 numeric(19, 2) not null default 0,
    commission              numeric(19, 2) not null default 0,
    commission_vat          numeric(19, 2) not null default 0,
