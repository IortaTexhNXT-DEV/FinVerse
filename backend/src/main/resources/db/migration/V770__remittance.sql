    incentive_vat           numeric(19, 2) not null default 0,
    net_due                 numeric(19, 2) not null default 0,
    submitted_by            varchar(50),
    submitted_at            timestamptz,
    approved_by             varchar(50),
    approved_at             timestamptz,
    return_reason           varchar(250),
    disbursement_request_no varchar(30),
    disbursement_status     varchar(20),
    dv_no                   varchar(40),
    disbursed_amount        numeric(19, 2),
    commission_or_no        varchar(40),
    commission_or_status    varchar(20),
    incentive_or_no         varchar(40),
    incentive_or_status     varchar(20),
    or_message              varchar(500),
    schedule_sent_at        timestamptz,
    schedule_sent_by        varchar(50),
    extract_file_id         bigint,
    created_at              timestamptz    not null,
    created_by              varchar(50)    not null,
    updated_at              timestamptz,
    updated_by              varchar(50)
);
create index ix_rem_batch_stage on rem_batch (company_id, stage);
create index ix_rem_batch_insurer on rem_batch (company_id, insurer_code, remittance_type);

create table rem_batch_line (
