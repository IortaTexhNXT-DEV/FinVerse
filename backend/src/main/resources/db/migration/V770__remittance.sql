-- =====================================================================================
-- iNXT BrokerVerse - V770 Remittance (BDOI Operations BRD-2, OPERATIONS_DESIGN 4.3)
--   * Extraction runs and per-invoice extraction tags (RMTID.001/003/004/005/006/014/017/020,
--     tags EXTRACTED / UNEXTRACTED_NOT_DUE / UNEXTRACTED_DUE / RETURNED);
--   * remittance batches RMB-<insurer>-<yyyy> and their lines (RMTID.002/007-011/019/029/036),
--     exclusions with reason, user and restore (RMTID.002 addendum), insurer OR details and
--     the OR vs paid PR exception status (RMTID.012/013/016), stored schedule and payment
--     request documents (RMTID.011);
--   * Marketing hold requests HLD-<yyyy> (RMTID.021/031, MKTID.002-007);
--   * special remittance requests SPR-<yyyy> (RMTID.030/033, MKTID.009);
--   * early-remittance incentive rules (RMTID.023; rates parked, OQ23);
--   * end-of-day extraction requests (RMTID.005; semantics parked, OQ18).
--   No foreign keys to V8xx tables: invoice no., ARN, client and insurer codes are plain values.
-- =====================================================================================

create table rem_extraction_run (
    id               bigint generated by default as identity primary key,
    version          bigint         not null default 0,
    company_id       bigint         not null references org_company (id),
    run_no           varchar(30)    not null unique,
    trigger_type     varchar(20)    not null check (trigger_type in ('SCHEDULED', 'MANUAL', 'MANUAL_INVOICE',
                                                                     'EOD_QUEUE', 'SPECIAL')),
    insurer_code     varchar(30),
    remittance_type  varchar(20),
    invoice_no       varchar(40),
    business_date    date           not null,
    started_at       timestamptz    not null,
    ended_at         timestamptz,
    status           varchar(20)    not null check (status in ('RUNNING', 'SUCCEEDED', 'FAILED')),
    examined_count   integer        not null default 0,
    extracted_count  integer        not null default 0,
    not_due_count    integer        not null default 0,
    due_count        integer        not null default 0,
    batch_count      integer        not null default 0,
    message          varchar(1000),
    created_at       timestamptz    not null,
    created_by       varchar(50)    not null,
    updated_at       timestamptz,
    updated_by       varchar(50)
);
create index ix_rem_extraction_run_company on rem_extraction_run (company_id, id desc);

create table rem_extraction_tag (
    id               bigint generated by default as identity primary key,
    version          bigint         not null default 0,
    run_id           bigint         references rem_extraction_run (id),
    company_id       bigint         not null references org_company (id),
    invoice_no       varchar(40)    not null,
    insurer_code     varchar(30)    not null,
    remittance_type  varchar(20),
    tag              varchar(30)    not null check (tag in ('EXTRACTED', 'UNEXTRACTED_NOT_DUE',
                                                            'UNEXTRACTED_DUE', 'RETURNED')),
    reasons          varchar(200),
    remarks          varchar(500),
    paid_ar          numeric(19, 2) not null default 0,
    dtip_balance     numeric(19, 2) not null default 0,
    remittable       numeric(19, 2) not null default 0,
    batch_no         varchar(40),
    created_at       timestamptz    not null,
    created_by       varchar(50)    not null,
    updated_at       timestamptz,
    updated_by       varchar(50)
);
create index ix_rem_extraction_tag_run on rem_extraction_tag (run_id);
create index ix_rem_extraction_tag_invoice on rem_extraction_tag (invoice_no, id desc);

create table rem_batch (
    id                      bigint generated by default as identity primary key,
    version                 bigint         not null default 0,
    company_id              bigint         not null references org_company (id),
    batch_no                varchar(40)    not null unique,
    insurer_code            varchar(30)    not null,
