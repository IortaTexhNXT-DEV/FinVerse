                             authorized_by, authorized_at, created_at, created_by)
select v.coverage, v.limit_amount, v.premium, date '2020-01-01', 'ACTIVE', 'SYSTEM', now(), now(), 'SYSTEM'
from (values
    ('BI', 50000, 170), ('BI', 100000, 285), ('BI', 200000, 460), ('BI', 300000, 600),
    ('BI', 500000, 850), ('BI', 750000, 1100), ('BI', 1000000, 1350),
    ('PD', 50000, 290), ('PD', 100000, 440), ('PD', 200000, 700), ('PD', 300000, 900),
    ('PD', 500000, 1200), ('PD', 750000, 1550), ('PD', 1000000, 1850)
