-- peril master, clause library and typed field rules.
--   PMADD01  one reusable hierarchy LOB > Subline / Type > Subtype > Coverage / Peril; a packaged
--            product cannot be saved without its cover type (the check below); naming convention
--            of risk codes as a per-line pattern (values wait for PQ02)
--   PMADD02  clause library (warranties, clauses, exclusions, deductible wordings) referenced by
--            the insurer x coverage terms of a package version (V814)
--   BRPM.003/004  field rules typed REQUIRED / LOV / RANGE / PATTERN
--   Design: docs/architecture/PRODUCT_MAINTENANCE_DESIGN.md sections 4.1 and 9.1.
--   Coverage and clause seeds are defaults for the Motor and Property packages until BDOI shares
--   the product matrix (Q01, PQ02); they are maintained on the Coverages & Clauses screen under
--   maker-checker (PRODUCT_MAINTAIN / PRODUCT_AUTHORIZE).
