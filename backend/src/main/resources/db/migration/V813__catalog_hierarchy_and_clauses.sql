-- ---------- Hierarchy: subtype under a cover type (depth at most 2, same line) ----------------
alter table cat_cover_type add column parent_code varchar(30);
alter table cat_cover_type add constraint fk_cat_cover_type_parent
    foreign key (line_code, parent_code) references cat_cover_type (line_code, code);
alter table cat_cover_type add constraint ck_cat_cover_type_parent
    check (parent_code is null or parent_code <> code);

-- Naming convention of new risk codes of a line, as a regular expression (PMADD01 AC3, PQ02).
alter table cat_product_line add column code_pattern varchar(120);

-- Every seeded packaged product has a cover type; from now on it is mandatory (PMADD01).
alter table cat_product add constraint ck_cat_product_package_cover
    check (not packaged or cover_type_code is not null);

-- ---------- Coverage / peril master (PMADD01) ---------------------------------------------------
create table cat_coverage (
    id            bigint generated by default as identity primary key,
    version       bigint       not null default 0,
    line_code     varchar(30)  not null references cat_product_line (code),
    code          varchar(30)  not null,
    name          varchar(150) not null,
    kind          varchar(20)  not null,
    basic         boolean      not null default false,
    sort_order    integer      not null default 0,
    record_status varchar(30)  not null,
    authorized_by varchar(50),
    authorized_at timestamptz,
    created_at    timestamptz  not null,
    created_by    varchar(50)  not null,
    updated_at    timestamptz,
    updated_by    varchar(50),
    constraint uq_cat_coverage unique (line_code, code)
);

-- ---------- Clause library (PMADD02) -----------------------------------------------------------
create table cat_clause (
    id             bigint generated by default as identity primary key,
    version        bigint       not null default 0,
    code           varchar(30)  not null unique,
    kind           varchar(20)  not null,
    -- null = every line
    line_code      varchar(30)  references cat_product_line (code),
    title          varchar(200) not null,
    wording        text         not null,
    effective_from date         not null,
    effective_to   date,
    record_status  varchar(30)  not null,
    authorized_by  varchar(50),
    authorized_at  timestamptz,
    created_at     timestamptz  not null,
    created_by     varchar(50)  not null,
    updated_at     timestamptz,
    updated_by     varchar(50),
    constraint ck_cat_clause_dates check (effective_to is null or effective_to >= effective_from)
);
create index ix_cat_clause_line on cat_clause (line_code);

-- ---------- Typed field rules (BRPM.004) --------------------------------------------------------
alter table cat_field_rule add column rule_type varchar(10) not null default 'REQUIRED';
alter table cat_field_rule add column lov_type varchar(40);
alter table cat_field_rule add column min_value numeric(19, 2);
alter table cat_field_rule add column max_value numeric(19, 2);
alter table cat_field_rule add column pattern varchar(200);
alter table cat_field_rule add constraint ck_cat_field_rule_type
    check (rule_type in ('REQUIRED', 'LOV', 'RANGE', 'PATTERN')
        and (rule_type <> 'LOV' or lov_type is not null)
        and (rule_type <> 'RANGE' or min_value is not null or max_value is not null)
        and (rule_type <> 'PATTERN' or pattern is not null)
        and (min_value is null or max_value is null or max_value >= min_value));

