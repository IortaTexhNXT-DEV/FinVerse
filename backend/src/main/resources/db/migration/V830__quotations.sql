values ('NB_QUOTATION', 'APPROVED', 'revise', 'DRAFT', 'Revise (new version)', 'QUOTE_MAINTAIN', false, null, 50),
       ('NB_QUOTATION', 'SENT_TO_CLIENT', 'revise', 'DRAFT', 'Revise (new version)', 'QUOTE_MAINTAIN', false, null, 50);

