                       authorized_by, authorized_at, created_at, created_by)
select 'DOCUMENT_TYPE', v.code, v.label, v.sort_order, date '2020-01-01', 'ACTIVE', 'SYSTEM', now(), now(), 'SYSTEM'
from (values ('QUOTATION_SLIP', 'Quotation slip', 51),
             ('INSURER_RESPONSE', 'Insurer response / terms', 52),
             ('COMPARATIVE_TABLE', 'Comparative table', 53),
             ('PROPOSAL_SLIP', 'Proposal slip', 54)) as v(code, label, sort_order);

