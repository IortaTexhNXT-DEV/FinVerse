    note          varchar(500),
    file_ref      varchar(80),
    created_at    timestamptz   not null,
    created_by    varchar(50)   not null,
    updated_at    timestamptz,
    updated_by    varchar(50),
    constraint ck_dsb_instrument_event_source check (source in ('USER', 'SYSTEM', 'UPLOAD', 'JOB'))
);
create index ix_dsb_instrument_event on dsb_instrument_event (instrument_id, id);

create table dsb_voucher_tag (
    id              bigint generated by default as identity primary key,
    version         bigint         not null default 0,
