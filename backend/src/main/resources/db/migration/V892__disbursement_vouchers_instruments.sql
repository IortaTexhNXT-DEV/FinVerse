create table dsb_funding_request (
    id                     bigint generated by default as identity primary key,
    version                bigint         not null default 0,
    company_id             bigint         not null references org_company (id),
    funding_no             varchar(30)    not null,
    source_bank_account_id bigint         not null references pay_bank_account (id),
    target_bank_account_id bigint         not null references pay_bank_account (id),
    amount                 numeric(19, 2) not null,
    currency               varchar(3)     not null,
    purpose                varchar(500)   not null,
    value_date             date           not null,
    stage                  varchar(20)    not null,
    verified_by            varchar(50),
    first_approver         varchar(50),
    second_approver        varchar(50),
    bob_reference          varchar(80),
    journal_no             varchar(30),
    created_at             timestamptz    not null,
    created_by             varchar(50)    not null,
    updated_at             timestamptz,
    updated_by             varchar(50),
    constraint uq_dsb_funding_no unique (funding_no),
    constraint ck_dsb_funding_amount check (amount > 0),
    constraint ck_dsb_funding_accounts check (source_bank_account_id <> target_bank_account_id),
    constraint ck_dsb_funding_stage check (stage in ('CREATED', 'FOR_VERIFICATION', 'FOR_APPROVAL_1',
        'FOR_APPROVAL_2', 'APPROVED', 'DECLINED', 'CANCELLED'))
);
create index ix_dsb_funding_stage on dsb_funding_request (company_id, stage);
