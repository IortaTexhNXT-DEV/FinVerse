insert into sec_role (code, name, description, privilege_level, created_at, created_by)
select p.code, p.name, p.description, p.privilege_level, now(), 'SYSTEM'
from bdoi_profile p
where not exists (select 1 from sec_role r where r.code = p.code);

update sec_role r
set name = p.name, description = p.description, privilege_level = p.privilege_level, active = true,
    updated_at = now(), updated_by = 'SYSTEM'
from bdoi_profile p
where r.code = p.code
  and (r.name <> p.name or r.description is distinct from p.description
       or r.privilege_level <> p.privilege_level or not r.active);

delete from sec_role_permission rp
using sec_role r
where rp.role_id = r.id
  and r.code in (select code from bdoi_profile)
  and not exists (select 1 from bdoi_profile_permission g where g.code = r.code and g.permission = rp.permission);

insert into sec_role_permission (role_id, permission)
select r.id, g.permission
from bdoi_profile_permission g
join sec_role r on r.code = g.code
where not exists (select 1 from sec_role_permission x where x.role_id = r.id and x.permission = g.permission);
