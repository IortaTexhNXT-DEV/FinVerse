"""Shared helpers of the standard document set of a BRD in BDOI's template (FRS, BPS, UXD, RNO, ICD, DSP, DDI, USR,
workbooks, How to read this pack) and of the programme documents (NFR, Glossary, Decision and Observation Log,
Document Register).

* ``PackDoc``     a Word document started from BDOI's template D051 (templates/bdoi_d051_frs_template.docx): cover,
                  document details, revision log, table of contents, headers and footers kept; the body is written with
                  h1 / h2 / para / bullets / table.
* ``workbook``    a BIBS review workbook (cover, README, Lists sheet with the drop-down values, frozen headers).
* ``finish``      writes the table of contents, checks the wording, converts to PDF (not kept in git).
* ``wording``     the checks every client document passes: restricted words, development-status wording and internal
                  references (as tools/deliverables/check_pack.py), filler words, personal names.

Every builder of a BRD pack (build_pack.py) and of the programme documents (build_programme_common.py) uses these, so
that a new BRD needs only its content module.
"""

