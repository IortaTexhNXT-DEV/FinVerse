import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

from docx.oxml.ns import qn

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[4]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO / "tools" / "deliverables"))
import brd_common_final as final  # noqa: E402
import build_brd11_interface_spec as icd  # noqa: E402
from brd11_xlsx import Column, ReviewWorkbook  # noqa: E402,F401

TEMPLATE = HERE / "templates" / "bdoi_d051_frs_template.docx"
OUT_PROGRAMME = REPO / "docs" / "deliverables" / "out" / "Programme"
OUT_BDOI = OUT_PROGRAMME / "BDOI_Template_FRS"
OUT_COMMON = OUT_PROGRAMME / "Common"
PREPARED = "iorta TechNXT Project Team"
# The template's placeholder author and the names of persons that never appear in a document.
TEMPLATE_AUTHOR = codecs.decode("Wbua Oneonpunab", "rot13")  # kept encoded: no name in the sources
FILLER = re.compile(r"\b(leverag\w*|seamless\w*|robust\w*|delv\w+|comprehensive solution|cutting-edge|"
                    r"state-of-the-art|synerg\w+|empower\w*|holistic|best-in-class|game-chang\w+)\b", re.I)
TOOL_WORDS = re.compile(r"\b(AI|GPT|generated by|assistant|prompt)\b")


@dataclass
class DocMeta:
    file: str
    cover: str
    header_left: str
    header_right: str
    doc_no: str
    version: str
    date_us: str
    created_us: str
    revisions: list[tuple[str, str, str, str]] = field(default_factory=list)


class PackDoc(icd.Spec):
    """A document of a pack in BDOI's template with a new body."""

    def __init__(self, meta: DocMeta):
        super().__init__(TEMPLATE)
        self.meta = meta
        self._cover()
        self.revision_log(meta.revisions)
        self.page_break()

    def _cover(self) -> None:
        m = self.meta
        body = self.doc.element.body
        for t in list(body)[0].iter(qn("w:t")):
            if "Brokering System (BIBS)" in (t.text or ""):
                t.text = f" Brokering System (BIBS) - {m.cover} "
            elif t.text == TEMPLATE_AUTHOR:
                t.text = PREPARED
        details = next(e for e in body if e.tag == qn("w:tbl")
                       and "Template Reference" in "".join(t.text or "" for t in e.iter(qn("w:t"))))
        values = {"Document No.": m.doc_no, "FR Document No.": m.doc_no, "Prepared by:": PREPARED,
                  "Drafting support:": PREPARED, "Revision No.": m.version, "Last Updated by:": PREPARED,
                  "Last Updated Date:": m.date_us, "Creation Date:": m.created_us}
        for tr in details.iter(qn("w:tr")):
            tcs = tr.findall(qn("w:tc"))
            label = "".join(t.text or "" for t in tcs[0].iter(qn("w:t"))).strip()
            for k, v in values.items():
                if label.replace(" ", "") == k.replace(" ", ""):
                    icd._set_tc(tcs[-1], v)
            if label.startswith("FR Document"):
                icd._set_tc(tcs[0], "Document No.", bold=True)
        for s in self.doc.sections:
            for part in (s.header, s.first_page_header, s.even_page_header):
                for p in part.paragraphs:
                    for r in p.runs:
                        if r.text in ("Functional Requirements Specification", icd.C.HEADER_LEFT):
                            r.text = m.header_left
                        elif "BIBS" in r.text and ("User Access" in r.text or "Brokering" in r.text):
                            r.text = m.header_right

    def h1(self, text: str, new_page: bool = True) -> None:
        self.heading(text, 1, new_page=new_page)

    def h2(self, text: str) -> None:
        self.heading(text, 2)

    def h3(self, text: str) -> None:
        self.heading(text, 3)

    def kv(self, rows: list[tuple[str, str]], caption: str | None = None, widths=(2.6, 6.6)) -> None:
        self.table(["Item", "Value"], rows, list(widths), caption=caption)


def workbook(title: str, kind: str, brd: str, version: str, date: str, subtitle: str) -> ReviewWorkbook:
    return ReviewWorkbook(title, doc_type=kind, brd=brd, version=version, date=date, subtitle=subtitle)


def wording(lines: list[str], name: str) -> list[str]:
    """Words a client document may not contain (check_pack rules, filler, tool words, the template author)."""
    import check_pack as cp  # noqa: PLC0415
    hits = set()
    for t in lines:
        for label, pat in cp.BUILD_STATUS:
            hits |= {f"{label}: {m.group(0)}" for m in pat.finditer(t)}
        hits |= {f"restricted: {m.group(0)}" for m in cp.RESTRICTED.finditer(t)}
        hits |= {f"filler: {m.group(0)}" for m in FILLER.finditer(t)}
        hits |= {f"tool word: {m.group(0)}" for m in TOOL_WORDS.finditer(t)}
        if codecs.decode("Oneonpunab", "rot13") in t:
            hits.add("personal name")
    return [f"{name}: {h}" for h in sorted(hits)]


def check_file(path: Path) -> None:
    import check_pack as cp  # noqa: PLC0415
    problems = wording(cp.office_lines(path), path.name)
    if problems:
        raise SystemExit("wording refused in client documents:\n  " + "\n  ".join(problems[:40]))


def finish(doc: PackDoc, target: Path, tmp: Path, pdf: bool = True) -> int:
    """Saves the document, writes its table of contents, checks it, and converts it to PDF beside it."""
    work = tmp / target.name
    doc.save(work)
    n = final.populate_toc(work)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(work, target)
    check_file(target)
    if pdf:
        to_pdf(target)
    return n


def to_pdf(target: Path) -> None:
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", str(target.parent), str(target)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def pdf_pages(pdf: Path) -> int:
    if not pdf.exists():
        return 0
    data = pdf.read_bytes()
    return len(re.findall(rb"/Type\s*/Page[^s]", data))


def save_workbook(wb: ReviewWorkbook, target: Path) -> Path:
    target.parent.mkdir(parents=True, exist_ok=True)
    wb.save(target)
    check_file(target)
    return target


def retire(old: Path) -> None:
    """Removes a superseded file of out/ (and its PDF) from the working tree; git records the removal."""
    for p in (old, old.with_suffix(".pdf")):
        if p.exists():
            p.unlink()
