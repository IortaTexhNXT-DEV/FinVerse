import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { RotateCw } from 'lucide-react';
import { useState } from 'react';
import { canResend, periodStart, siBatchApi } from '@/api/siBatches';
import type { SiBatch } from '@/api/siBatches';
import { useAuth } from '@/auth/authContext';
import { Amount } from '@/components/ui/Amount';
import { Button } from '@/components/ui/Button';
import { Card } from '@/components/ui/Card';
import { DataTable } from '@/components/ui/DataTable';
import { ErrorAlert } from '@/components/ui/ErrorAlert';
import { PageHeader } from '@/components/ui/PageHeader';
import { StatusBadge } from '@/components/ui/StatusBadge';
import { useToast } from '@/components/ui/toastContext';
import { useCompanyId } from '@/context/workspaceContext';
import { TextInput } from '@/features/assets/FormControls';
import { formatDate, formatDateTime, today } from '@/utils/format';
import { ServiceInvoiceTable } from './InvoiceTabs';
import './booking.css';

function BatchItems({ batch }: Readonly<{ batch: SiBatch }>) {
  const items = useQuery({
    queryKey: ['booking', 'si-batches', 'items', batch.id],
    queryFn: () => siBatchApi.items(batch.id),
  });
  return (
    <Card
      title={`Service invoices of ${batch.insurerName} on ${formatDate(batch.batchDate)}`}
      flush
    >
      <ErrorAlert error={items.error} />
      <ServiceInvoiceTable rows={items.data ?? []} loading={items.isLoading} />
    </Card>
  );
}

/**
 * Daily service-invoice batches (G09): one batch per insurer and business date, generated by the
 * SI_DAILY_BATCH job and e-mailed to the insurer, with its delivery status; a failed batch is sent
 * again from here.
 */
export default function SiBatchesPage() {
  const companyId = useCompanyId();
  const { can } = useAuth();
  const toast = useToast();
  const queryClient = useQueryClient();
  const [to, setTo] = useState(today());
  const [from, setFrom] = useState(periodStart(today()));
  const [open, setOpen] = useState<SiBatch | null>(null);
  const rows = useQuery({
    queryKey: ['booking', 'si-batches', companyId, from, to],
    queryFn: () => siBatchApi.list(companyId, from, to),
    enabled: companyId > 0 && from !== '' && to !== '',
  });
  const resend = useMutation({
    mutationFn: (batch: SiBatch) => siBatchApi.resend(batch.id),
    onSuccess: async (batch) => {
      await queryClient.invalidateQueries({ queryKey: ['booking', 'si-batches'] });
      toast.success(`Batch of ${batch.insurerName} sent again`);
    },
  });
  const process = can('BOOKING_PROCESS');
  return (
    <div className="stack">
      <PageHeader
        section="Booking"
        title="Service Invoice Batches"
        description="The service invoices of each insurer and day, e-mailed in one batch by the daily job."
      />
      <ErrorAlert error={rows.error ?? resend.error} />
      <Card>
        <div className="stack">
          <div className="form-grid">
            <TextInput label="From" type="date" value={from} onChange={setFrom} />
            <TextInput label="To" type="date" value={to} onChange={setTo} />
          </div>
          <DataTable<SiBatch>
            loading={rows.isLoading}
            rows={rows.data ?? []}
            rowKey={(b) => b.id}
            emptyMessage="No batch for the period."
            columns={[
              { key: 'd', header: 'Date', render: (b) => formatDate(b.batchDate) },
              {
                key: 'i',
                header: 'Insurer',
                render: (b) => (
                  <Button size="sm" variant="ghost" onClick={() => setOpen(b)}>
                    {b.insurerName}
                  </Button>
                ),
              },
              { key: 'n', header: 'Invoices', numeric: true, render: (b) => b.itemCount },
              { key: 'c', header: 'Currency', render: (b) => b.currency ?? 'Several' },
              {
                key: 'm',
                header: 'Commission',
                numeric: true,
                render: (b) => <Amount value={b.commissionTotal} />,
              },
              {
                key: 't',
                header: 'Net',
                numeric: true,
                render: (b) => <Amount value={b.netTotal} />,
              },
              { key: 's', header: 'Delivery', render: (b) => <StatusBadge status={b.status} /> },
              { key: 'a', header: 'Attempts', numeric: true, render: (b) => b.attempts },
              { key: 'e', header: 'Sent to', render: (b) => b.recipientEmail ?? '' },
              { key: 'w', header: 'Sent', render: (b) => formatDateTime(b.sentAt) },
              { key: 'r', header: 'Reason', render: (b) => b.lastError ?? '' },
              {
                key: 'x',
                header: 'Actions',
                render: (b) =>
                  process &&
                  canResend(b) && (
                    <Button
                      size="sm"
                      variant="secondary"
                      icon={<RotateCw size={14} />}
                      busy={resend.isPending && resend.variables.id === b.id}
                      onClick={() => resend.mutate(b)}
                    >
                      Re-send
                    </Button>
                  ),
              },
            ]}
          />
        </div>
      </Card>
      {open && <BatchItems batch={open} />}
    </div>
  );
}
